// ══════════════════════════════════════════════════════════════════
//  DARK ACID 08  ·  Strudel  ·  180 BPM
//
//  Третий характер, а не версия. 06 — глубокий даб на 122, 07 — дарк-техно
//  на 126, этот — дарк-эйсид на 180: между хард-эйсидом, дарк-трансом и
//  габбером. Задача была «шершавый звук, жирная бочка, чтоб ноги сами
//  в пляс», поэтому всё построено вокруг двух вещей: 303-линия и бочка.
//  Всё остальное — обслуживает их.
//
//  ── ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ 07 ────────────────────────────────────
//   1. ГАРМОНИЯ СТОИТ. В 07 корни шли по восьми тактам (c db f ab eb bb db g).
//      Здесь корень один и тот же, а движение даёт ход a → bb → a: i–bII–i,
//      фригийский сдвиг на полутон. Это дарк-транс: дрон не гуляет, он
//      поднимается на полтона и опускается. 180 BPM такую музыку держит
//      только если низ стабилен.
//   2. МЕЛОДИИ НЕТ. В 07 была мелодия, пусть и тревожная. Здесь её роль
//      играет 303-линия: она тема и грув. А НИЗ держит отдельная дорожка
//      BASS (a1…f2) — первая версия пыталась заставить 303 быть и тем и
//      другим, и линия уехала в свисток a3…c5. Теперь полосы разведены:
//      бас 55–87 Гц, линия 110–260, пэд 220–390.
//      Линия хроматическая (a c bb eb f) — это норма для эйсида, не грязь.
//   3. БОЧКА ДРУГАЯ. Не сэмпл с фильтром, а сэмпл, который РАСТЯНУТ по
//      высоте (`speed` = kickTune) и раздавлен вейвшейпером. 0.75 по speed
//      превращает 909-бочку в габбер: ниже, длиннее, грязнее.
//
//  ── ПОЧЕМУ ЗВУК ШЕРШАВЫЙ ────────────────────────────────────────
//  Четыре разных инструмента, каждый на своём месте — это не «побольше
//  дисторшна везде», а четыре разных вида грязи:
//   • shape   — вейвшейпер (мягкое ограничение). Бочка, эйсид-крик.
//   • distort — клиппинг с выбором типа. Хувер: ему нужен срыв.
//   • crush   — бит-крушер. Эйсид-крик и клэп: цифровая рвань.
//   • drive   — подгруз САМОГО фильтра (только для ladder). Внутри это
//               exp(drive), то есть drive 1 ≈ усиление 2.7, drive 2.6 ≈ 13.
//               Фильтр не просто режет — он перегружается на резонансе,
//               и это главный источник «шершавости» у 303.
//  Плюс ftype("ladder") у эйсида: лестничный фильтр злее 24db, у него
//  резонанс не свистит, а рычит.
//
//  ── 🛑 ПОЧЕМУ ЭТО НЕ ЖРЁТ ПРОЦ (важно при правках) ──────────────
//  `shape`, `crush`, `coarse`, `distort` и `ftype("ladder")` — это НЕ
//  нативные ноды, а AudioWorklet: superdough вызывает `new AudioWorkletNode`
//  на КАЖДОЕ событие и никогда их не переиспользует (biquad-фильтры, наоборот,
//  берутся из пула). Создание worklet — самая дорогая операция в этом движке,
//  поэтому цена слоя = число событий в такт × число worklet'ов в цепочке.
//  Первая версия трека на 180 BPM давала ~180 worklet'ов на такт, то есть
//  ~540 в секунду — звук захлёбывался на слабой машине. Что сделано:
//   • хэты (58 событий/такт) — shape снят совсем, это был главный счёт;
//   • ролл (16) и сирена (8) — тоже без shape;
//   • эйсид: остался один worklet (ladder), shape и crush ушли на крик;
//   • крик и переключаемая линия — 24db (biquad из пула) вместо ladder;
//   • бочка: режимы 0 и 1 были двумя одинаковыми ветками, теперь одна.
//  Осталось ~45 worklet'ов на такт (~135 в секунду) вместо ~180 (540) — вчетверо
//  меньше. Больше половины остатка — слой крика (shape + crush на десяти нотах),
//  который по умолчанию молчит; если машина всё равно не тянет, начни с него.
//  Правило на будущее: worklet можно ставить только туда, где событий мало
//  (бочка, клэп, хувер), и нельзя — на 16-е хэты и на линию.
//
//  ── ЭЙСИД: КАК СДЕЛАНА 303 ─────────────────────────────────────
//  Классическая 303 — это не «пила с фильтром», это три вещи вместе:
//   1. ФИЛЬТР-ОГИБАЮЩАЯ. lpenv + очень короткий lpa (2 мс) + короткий lpd.
//      Каждая нота — «квак»: фильтр открывается и падает внутри ноты.
//      Без этого получается просто пила.
//   2. АКЦЕНТЫ. В 303 акцент — это громче И ярче одновременно. Здесь
//      gain-паттерн на 16 шагов, он же задаёт грув.
//   3. ПОДЪЕЗДЫ. Родного slide в 1.2.6 нет (в движке это заглушка), поэтому
//      slide сделан через питч-огибающую. В superdough она устроена так:
//      min = питч в НАЧАЛЕ атаки, max = в КОНЦЕ, а panchor сдвигает обе
//      границы. panchor(1) → старт на penv полутонов НИЖЕ ноты, max = 0.
//      Значит подъём занимает ровно pattack — поэтому время подъезда это
//      слайдер, а не 1 мс (на 1 мс подъезда просто не слышно: нота прыгает
//      на место мгновенно). acidSlide = глубина, acidSlideTime = длина,
//      паттерн penv — в какие 16-е въезд есть. Это ближе к живой 303, чем
//      ровное портаменто на всех нотах.
//
//  ── РЕЖИМЫ ──────────────────────────────────────────────────────
//  УДАРНЫЕ (mode, 5 штук — в 06 и 07 было четыре):
//    0 — ТОПОТ: бочка четыре в пол, открытые хэты на «и». Рейв.
//    1 — ГАББЕР: то же плюс снейр на 2 и 4. Хардкор-бэкбит.
//    2 — ЛОМ: бочка синкопами, снейр на 2 и 4, хэты рваные.
//    3 — БРЕЙК: половинный темп, бочка на 1 и 3, огромный снейр.
//    4 — РОЛЛ: 16-е бочки. Это и есть габбер — 12 ударов в секунду.
//  ГАРМОНИЯ (harmony): 0 — квинты без терций, 1 — минорные трезвучия.
//  ЭЙСИД (acidMode): 0 — низкий риф, 1 — тот же рисунок октавой выше.
//
//  ── ПОЧЕМУ НЕ НАДОЕДАЕТ ─────────────────────────────────────────
//  Длины не совпадают: воздух 16, винил 12, перкуссия 5, брейк-филл 4,
//  остальное 8. Плюс рандом: sometimesBy на хэтах и эйсиде, degradeBy на
//  блипах, pan по rand. Общий цикл — сотни тактов.
//
//  ── СТАРТ ───────────────────────────────────────────────────────
//  Звучит сразу только атмосфера: воздух 0.10, дрон 0.16, винил 0.04.
//  Порядок подъёма — в шпаргалке внизу файла.
// ══════════════════════════════════════════════════════════════════

