// ══════════════════════════════════════════════════════════════════
//  BERLIN TECHNO 01  ·  Strudel  ·  130 BPM
//
//  Холодное техно. 4/4 без передышки, никаких аккордов: ни пэда, ни
//  задержек, ни одновременных разных нот. Бас — одна линия на c,
//  в которую врезаются тритон (f#), малая секунда (db), малая терция
//  (eb) и малая секста (ab). Мелодия — FM-колокольчик, живёт на
//  девятых (d, db), поэтому джазово, но никуда не разрешается.
//
//  СТАРТ: тишина и воздух. Все инструменты по умолчанию на 0, включая
//  бочку; слышен только шум (noiseVol 0.22) — комната до того, как
//  войдёт бочка. Дальше поднимаешь слайдеры сам, в любом порядке.
//  Бочка по умолчанию глухая (kickCut 1600) — если нужен щелчок,
//  тяни kickCut вверх.
//
//  Длина. Такты не сходятся друг с другом специально:
//      бас        8 тактов
//      мелодия    7 тактов
//      перкуссия  5 тактов
//      хэты       4 такта (лом через every)
//      шум       16 тактов
//  Общий цикл 560 тактов ≈ 17 минут при 130 BPM. То есть трек не
//  повторяется — «чередующиеся паттерны» получаются сами, без
//  заранее расписанной аранжировки.
// ══════════════════════════════════════════════════════════════════

const BPM = 130
setcpm(BPM / 4) // один цикл = один такт 4/4 (≈ 1.846 с)

// ──────────────────────────────────────────────────────────────────
//  ПУЛЬТ   slider(значение, минимум, максимум, шаг)
// ──────────────────────────────────────────────────────────────────

// ТРИ РЕЖИМА БАРАБАНОВ. Кнопок в Strudel нет, поэтому слайдер с шагом 1.
//   0 — классика: открытые хэты на «и», клэп на 2 и 4, перкуссия
//   1 — сухо:    закрытые шестнадцатые, клэп реже, перкуссии нет
//   2 — лом:     смещённые хэты, клэп не на месте, перкуссия чаще
// Бочка не глохнет ни в одном режиме — она якорь.
const mode = slider(0, 0, 2, 1)
const m0 = mode.fmap((m) => (m === 0 ? 1 : 0))
const m1 = mode.fmap((m) => (m === 1 ? 1 : 0))
const m2 = mode.fmap((m) => (m === 2 ? 1 : 0))

// МАСТЕР-ФИЛЬТР на верх (хэты, клэп, перкуссия) — главная ручка сета.
// Срез + резонанс + медленный LFO: один и тот же жест, что делает диджей.
const masterCut  = slider(12000, 200, 16000, 100) // срез верха, Гц
const masterRes  = slider(2, 0, 20, 0.5)          // резонанс на срезе
const masterHpf  = slider(260, 20, 2000, 10)      // хайпасс верха (билд-ап)
const masterLfo  = slider(0, 0, 6, 0.1)           // качок среза, × срез
const masterLfoR = slider(0.125, 0.03, 2, 0.005)  // скорость: 0.125 = раз в 8 тактов

const verb = slider(0.25, 0, 1, 0.01) // общий реверб
const duck = slider(0.4, 0, 1, 0.01)  // сайдчейн баса от бочки

// БОЧКА — по умолчанию тоже 0: старт с одного воздуха. Срез низкий,
// чтобы при подъёме она звучала глухо, а не щёлкала.
const kickVol   = slider(0, 0, 1.4, 0.01)     // громкость
const kickShape = slider(0.4, 0, 0.95, 0.01)  // жёсткость
const kickCut   = slider(1600, 500, 16000, 100) // срез бочки: низко = глухо
const rumbleVol = slider(0, 0, 1, 0.01)       // низкий «румбл» под бочкой
const rumbleCut = slider(170, 60, 500, 5)     // его срез

// БАРАБАНЫ
const hatVol  = slider(0, 0, 1, 0.01)      // закрытые хэты
const ohVol   = slider(0, 0, 1, 0.01)      // открытые хэты (режим 0)
const clapVol = slider(0, 0, 1, 0.01)      // клэп
const percVol = slider(0, 0, 0.9, 0.01)    // перкуссия
const hatRoll = slider(0, 0, 1, 0.01)      // вероятность «дробей» на хэтах
const percEcho = slider(0.35, 0, 0.9, 0.01) // дилей на клэпе/перкуссии

// БАС — два слоя: пила (то, что слышно) и синус на октаву ниже (вес)
const bassVol   = slider(0, 0, 1.4, 0.01)  // пила
const subVol    = slider(0, 0, 1, 0.01)    // синус
const bassCut   = slider(260, 60, 2000, 10) // срез в закрытом виде, Гц
const bassEnv   = slider(3.2, 0, 8, 0.1)   // раскрытие фильтра, октавы
const bassDecay = slider(0.2, 0.02, 1.2, 0.01) // длина ноты, с
const bassLfo   = slider(2, 0, 10, 0.5)    // качок фильтра внутри ноты
const bassLfoR  = slider(2, 0.5, 8, 0.5)   // качков на такт
const bassReso  = slider(9, 0, 26, 0.5)    // резонанс
const bassDrive = slider(0.35, 0, 0.95, 0.01) // дисторшн
const bassGhost = slider(0.15, 0, 0.8, 0.01) // вероятность дабл-нот
const bassRand  = slider(0.15, 0, 0.6, 0.01) // разброс фильтра от ноты к ноте

// МЕЛОДИЯ — FM-колокольчик
const melVol  = slider(0, 0, 1, 0.01)      // громкость
const melCut  = slider(2600, 200, 9000, 20) // срез
const melReso = slider(2, 0, 20, 0.5)      // резонанс
const melFm   = slider(2.2, 0, 8, 0.1)     // индекс FM (яркость/металл)
const melFmh  = slider(2.41, 0.5, 8, 0.01) // гармоничность: нецелая = холод
const melFmD  = slider(0.12, 0.01, 0.6, 0.01) // спад FM: удар яркий, хвост тусклый
const melFmS  = slider(0.15, 0, 1, 0.01)   // сколько металла остаётся после удара
const melEcho = slider(0.45, 0, 0.9, 0.01) // дилей
const melFb   = slider(0.55, 0, 0.9, 0.01) // обратная связь дилея
const melPan  = slider(0.35, 0, 1, 0.01)   // разброс по панораме

// ШУМ — воздух/шипение, которым техно дышит. Единственное, что звучит
// сразу: комната должна быть слышна до того, как войдёт бочка.
const noiseVol = slider(0.22, 0, 0.6, 0.01)
const noiseCut = slider(1400, 100, 8000, 20)
const noiseLfo = slider(3, 0, 10, 0.5)

// 1 ± amt на каждую ноту: фильтр не повторяется от прохода к проходу
const jit = (amt) => rand.mul(2).sub(1).mul(amt).add(1)

// склейка списка тактов в одну фразу: <бар1 бар2 …> — по такту на элемент.
// ВАЖНО: m() тут обязателен, и это не украшение.
// Транспайлер REPL оборачивает в m() только строковые ЛИТЕРАЛЫ — строку,
// лежащую в переменной, он не видит. Без m() note(BASS) получает одну
// «ноту» из всего текста фразы, то есть не играет ничего. Проверено.
const phrase = (bars) => m('<' + bars.join(' ') + '>')

// ──────────────────────────────────────────────────────────────────
//  БОЧКА
// ──────────────────────────────────────────────────────────────────
$: s("bd*4")
  .gain(kickVol)
  .shape(kickShape)
  .lpf(kickCut)
  .duckorbit(2).duckdepth(duck).duckattack(0.05) // дакает бас (orbit 2)

// РУМБЛ — та самая берлинская низкая «пыль» под бочкой.
// Отдельная дорожка: длинный хвост, срез низко, дисторшн. По умолчанию 0.
$: s("bd*4")
  .gain(rumbleVol)
  .attack(0.004).decay(0.5).sustain(0)
  .lpf(rumbleCut).lpq(4)
  .shape(0.8)
  .room(0.2)

// ──────────────────────────────────────────────────────────────────
//  БАРАБАНОВ ТРИ РЕЖИМА  (mode 0 / 1 / 2)
// ──────────────────────────────────────────────────────────────────

// ХЭТЫ. hatVol работает во всех трёх режимах, ohVol — только открытые в 0-м.
$: stack(
     s("~ oh ~ oh ~ oh ~ oh").gain(ohVol.mul(m0)),                  // 0: открытые на «и»
     s("hh*16").gain(hatVol.mul("[.3 .12 .2 .12]*4").mul(m0)),       // 0: под ними тихие 16-е
     s("hh*16").gain(hatVol.mul("[1 .3 .6 .3]*4").mul(m1)),          // 1: сухие 16-е
     s("hh ~ hh:2 ~ hh ~ hh:2 ~").gain(hatVol.mul(m2)),              // 2: с дырами
   )
  .lpf(masterCut).lpq(masterRes).hpf(masterHpf)
  .lpdepth(masterLfo).lpsync(masterLfoR)
  .sometimesBy(hatRoll, (x) => x.ply(2))
  .every(4, (x) => x.ply(2)) // каждый 4-й такт хэты дробятся — тот самый «лом»

// КЛЭП
$: stack(
     s("~ ~ cp ~ ~ ~ cp ~").gain(clapVol.mul(m0)),       // 0: 2 и 4
     s("~ ~ cp:2 ~ ~ ~ ~ ~").gain(clapVol.mul(m1)),      // 1: реже
     s("~ cp ~ ~ ~ ~ cp:3 ~").gain(clapVol.mul(m2)),     // 2: не на месте
   )
  .room(verb).roomsize(4)
  .delay(percEcho).delaytime(0.375).delayfeedback(0.35)
  .hpf(masterHpf).lpf(masterCut).lpq(masterRes)

// ПЕРКУССИЯ — 5 тактов, поэтому не совпадает с басом (8) и мелодией (7)
$: s("<[~ ~ ~ rim ~ ~ ~ ~] [~ ~ rim ~ ~ ~ ~ rim] [~ ~ ~ ~ rim ~ rim ~] [~ ~ ~ ~ ~ ~ ~ rim] [rim ~ ~ ~ ~ rim ~ ~]>")
  .gain(percVol.mul(m0.add(m2))) // в режиме 1 её нет
  .delay(percEcho).delaytime(0.375).delayfeedback(0.5)
  .pan("<.6 .35 .75 .45 .6>")
  .hpf(masterHpf).lpf(masterCut).lpq(masterRes)

// 8 тактов баса, по строке на такт. Ритм — катящиеся восьмые «на и»
// (позиции 2, 6, 10, 14), в которые раз в пару тактов врезается
// цветная нота. Цвета: f#2 — тритон, db2 — малая секунда,
// eb2 — малая терция, ab2 — малая секста. Ни одна не разрешается,
// линия просто едет дальше — поэтому тонального центра нет.
const BASS = phrase([
  '[~ ~ c2 ~ ~ ~ c2 ~ ~ ~ c2 ~ ~ ~ c2 ~]', // 1
  '[~ ~ c2 ~ ~ ~ c2 ~ ~ ~ c2 ~ ~ ~ c2 ~]', // 2
  '[~ ~ c2 ~ ~ ~ c2 ~ ~ ~ f#2 ~ ~ ~ c2 ~]', // 3  тритон
  '[~ ~ c2 ~ ~ ~ c2 ~ ~ ~ c2 ~ ~ db2 c2 ~]', // 4  малая секунда на сломе
  '[~ ~ c2 ~ ~ ~ c2 ~ ~ ~ c2 ~ ~ ~ c2 ~]', // 5
  '[~ ~ c2 ~ ~ ~ eb2 ~ ~ ~ c2 ~ ~ ~ c2 ~]', // 6  малая терция
  '[~ ~ c2 ~ ~ ~ c2 ~ ~ ab2 ~ ~ ~ ~ c2 ~]', // 7  малая секста
  '[~ ~ c2 ~ ~ ~ c2 ~ ~ ~ f#2 ~ ~ db2 c2 ~]', // 8  тритон + секунда
])

// ──────────────────────────────────────────────────────────────────
//  БАС
//  Два слоя на одной линии: пила — то, что слышно, синус на октаву
//  ниже — то, что чувствуется. Линия 8 тактов, бочка её дакает.
// ──────────────────────────────────────────────────────────────────

$: stack(
     // пила: то, что слышно
     note(BASS).s("sawtooth").gain(bassVol),
     // синус на октаву ниже: то, что чувствуется
     note(BASS).add(note("-12")).s("sine").gain(subVol),
   )
  .lpf(bassCut).lpq(bassReso).ftype("24db")
  .lpenv(bassEnv.mul(jit(bassRand)))
  .lpa(0.004).lpd(0.09).lpsustain(0.4)
  .lpdepth(bassLfo.mul(jit(bassRand))).lpsync(bassLfoR).lpdc(0)
  .distort(bassDrive)
  .attack(0.002).decay(bassDecay).sustain(0.12).release(0.04)
  .sometimesBy(bassGhost, (x) => x.ply(2))
  .orbit(2)

// 7 тактов мелодии, по строке на такт. Ноты выбраны по интервалам к
// басу (c): d5 и db5 — большая и малая девятая (джазовый привкус),
// f#5 — тритон, ab4 — малая секста, eb5 — малая терция, c4 — тоника,
// которая никуда не ведёт. Семь тактов против восьми у баса — поэтому
// мелодия всё время съезжает относительно линии.
const MEL = phrase([
  '[c4 ~ ~ d5 ~ ~ ~ ~]', // 1  тоника, потом девятая
  '[~ ~ db5 ~ ~ ~ ~ ~]', // 2  малая девятая
  '[~ f#5 ~ ~ ~ ~ d5 ~]', // 3  тритон, потом девятая
  '[~ ~ ~ eb5 ~ ~ ~ ~]', // 4  малая терция
  '[d5 ~ ~ c4 ~ ~ ~ ~]', // 5  девятая падает в тонику
  '[~ ~ ~ ~ ~ ab4 ~ d5]', // 6  малая секста, девятая
  '[~ ~ db5 ~ ~ f#5 ~ ~]', // 7  малая девятая, тритон
])

// ──────────────────────────────────────────────────────────────────
//  МЕЛОДИЯ
//  Редко и сухо. FM с нецелой гармоничностью (fmh 2.41) — звук
//  металлический, не певучий. Никаких длинных нот: стаккато + дилей,
//  панорама пинг-понгом.
// ──────────────────────────────────────────────────────────────────

$: note(MEL)
  .s("sine")
  .fm(melFm).fmh(melFmh)
  .fmdecay(melFmD).fmsustain(melFmS) // удар металлический, хвост глохнет
  .decay(0.16).sustain(0).release(0.05)
  .lpf(melCut).lpq(melReso)
  .delay(melEcho).delaytime(0.375).delayfeedback(melFb)
  .room(verb)
  .pan(melPan.mul("<1 -1>")) // пинг-понг
  .gain(melVol)

// ──────────────────────────────────────────────────────────────────
//  ШУМ
//  Ровный воздух с медленно гуляющим срезом. Не событие, а фон:
//  им техно и дышит. По умолчанию 0.
// ──────────────────────────────────────────────────────────────────
$: s("white")
  .gain(noiseVol)
  .lpf(noiseCut).lpq(1)
  .lpdepth(noiseLfo).lpsync(0.0625) // один вдох на 16 тактов
  .room(verb)

// ──────────────────────────────────────────────────────────────────
//  ЧТО КРУТИТЬ ВО ВРЕМЯ ИГРЫ
//
//  старт:       слышен только воздух (noiseVol 0.22). Дальше kickVol 0.6,
//               потом hatVol 0.35, clapVol 0.5, subVol 0.5 + bassVol 0.6
//  бочка:       kickCut 1600 — глухо, 6000-9000 — щёлкает
//               kickShape 0.7 + rumbleVol 0.5 — злая и с низом
//  режимы:      mode 0 — классика, 1 — сухо и зло, 2 — ломаный грув.
//               Переключается на лету, бочка остаётся.
//  ФИЛЬТР ВЕРХА (главное):
//               masterCut 12000 → 300 медленно, на 8 тактов, и обратно —
//               это весь билд-ап и весь дроп, больше ничего не нужно
//               masterRes 8-14 — свист на срезе, 0 — сухо
//               masterHpf 800-2000 — вынести верх, оставив бочку и бас
//               masterLfo 3 + masterLfoR 0.125 — срез сам дышит раз в
//               8 тактов; masterLfoR 0.5 — раз в 2 такта, быстрее
//  бас:         bassCut 120 + bassEnv 5 — «взводится» на каждой ноте
//               bassCut 40 + bassReso 20 — почти закрыт, только щелчки
//               bassLfo 0 — ровный, 6 — дышит
//               bassGhost 0.5 — катящийся, вдвое больше нот
//               bassRand 0.4 — каждая нота со своим срезом
//  мелодия:     melFm 5 + melFmh 3.77 — стеклянный холод
//               melFmD 0.03 — только щелчок металла, 0.5 — звенит долго
//               melFmS 0 — глухой удар, 1 — металл до конца ноты
//               melEcho 0.7 + melFb 0.75 — уезжает в далёкий дилей
//               melCut 600 — призрак, 5000 — режет; melReso 12 — звенит
//  пустота:     mode 1, masterCut 2000, noiseVol 0.2, всё остальное вниз
//  румбл:       rumbleVol 0.5 + rumbleCut 140 — низкая пыль под бочкой
//
//  Хочешь 909 — добавь .bank('RolandTR909') к бочке/клэпу/хэтам.
// ──────────────────────────────────────────────────────────────────
