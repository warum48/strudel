// ══════════════════════════════════════════════════════════════════
//  DEEP DUB 05  ·  Strudel  ·  112 BPM
//
//  Отдельный трек, не версия 04. Медленнее (112 против 124), глубже,
//  26 дорожек против 12 — вдвое больше инструментов, и это не «ещё
//  два пэда», а слои: под-бочка, три вида баса, орган, арпеджио,
//  дабовый аккорд-хит, крошка, блипы, шумовой свип.
//
//  ── ГАРМОНИЯ: ОДНА ТОНАЛЬНОСТЬ, ДВА ВОICING'а ────────────────────
//  Раньше атонал и джаз были разными мирами, поэтому общая мелодия
//  между ними не жила. Здесь оба режима сидят в C эолийском
//  (c d eb f g ab bb) и различаются только укладкой:
//    0 — абстрактно: квартовые стеки БЕЗ терций. Ни мажора, ни минора,
//        ни разрешения — просто воздух. Это и есть «абстрактно, но не
//        грязно»: больше разрешённых нот, меньше трения.
//    1 — тепло: те же корни, но с 9-ми и 11-ми (Cm9, Abmaj9, Fm9,
//        Bbmaj9, Ebmaj9, Gm7). Ни одного доминантсептаккорда, поэтому
//        никуда не тянет и «соплей» нет.
//  Корни в обоих режимах одни и те же 8 тактов: c ab f bb eb g f ab.
//  Отсюда: переключение в любой момент не даёт ни одной грязной ноты,
//  а мелодия MEL_C играет в обоих режимах и всегда попадает в аккорд.
//
//  ── ЧТО ПЕРЕКЛЮЧАЕТСЯ, А ЧТО НЕТ ─────────────────────────────────
//  Переключаются: pad, stab, мелодия (у неё две версии — MEL_A/MEL_B).
//  Играют в обоих режимах: орган (только корень+квинта), общая мелодия
//  MEL_C, арпеджио TIA, бас. Это сделано намеренно — если бы всё
//  дёргалось разом, переключение звучало бы как смена трека.
//
//  ── TIA: АРПЕДЖИО «В СТИЛЕ», НЕ ЦИТАТА ──────────────────────────
//  Восходяще-нисходящая фигура шестнадцатыми по тонам Cm, фильтр
//  медленно открывается (lpsync 0.125 = раз в 8 тактов), длинный
//  дилей. Своя последовательность, не тема из сериала. По умолчанию
//  tiaVol = 0 — включается в середине, как «всем приятное».
//
//  ── ПОЧЕМУ НЕ НАДОЕДАЕТ ─────────────────────────────────────────
//  Длины фраз не совпадают: воздух 16, крошка 12, бас-призрак 12,
//  общая мелодия 12, мелодия A 7, мелодия B 4, бульки 5, перкуссия 5,
//  арпеджио 4, блипы 3, шумовой свип 16, остальное 8. Общий цикл — тысячи
//  тактов, то есть несколько часов до повтора целиком.
//  Плюс рандом: sometimesBy на мелодии, degradeBy на блипах, choose
//  на нотах, pan по rand. Ни один такт не гарантированно равен
//  предыдущему.
//
//  ── СТАРТ ───────────────────────────────────────────────────────
//  Звучит сразу только атмосфера: air 0.18, drone 0.09, винил 0.05,
//  pad 0.10. Всё остальное в нуле — поднимаешь по одной.
// ══════════════════════════════════════════════════════════════════

