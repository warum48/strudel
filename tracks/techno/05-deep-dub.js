// только тембр, он не делает тише.
//
// ПОЧЕМУ НЕ stut(). Внутри stut делает `pat.gain(pow(feedback, i))` — то есть
// ПЕРЕЗАПИСЫВАЕТ gain, а не умножает. Первая копия получает 1.0, остальные
// 0.55/0.30/0.17 — мимо clapVol. Отсюда «слайдер в ноль, а щелчки слышно»:
// четверть из них играла на полной громкости. Свой стутер: тот же ритм
// повторов и то же затухание, но gain УМНОЖАЕТСЯ, а не затирается.
const stutGain = (times, fb, step) => (x) =>
  x.echoWith(times, step, (p, i) =>
    p.withValue((v) => ({ ...v, gain: (v.gain ?? 1) * Math.pow(fb, i) })),
  )

