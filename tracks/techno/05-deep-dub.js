  '[bb2,d3,f3,c4]',   // Bbmaj9
  '[eb3,g3,bb3,f4]',  // Ebmaj9
  '[g3,bb3,d4,f4]',   // Gm7
  '[f3,ab3,c4,eb4]',  // Fm7
