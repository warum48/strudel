// ══════════════════════════════════════════════════════════════════
//  DARK TECHNO 07  ·  Strudel  ·  126 BPM
//
//  Отдельный трек, не версия 06. 06 — глубокий даб, этот — дарк-техно:
//  быстрее (126), жёстче, ниже, без «тепла» вообще. Задача была «тьма,
//  а то слишком светло», поэтому здесь нет ни одного мажорного аккорда
//  и ни одного разрешения в тонику на сильной доле.
//
//  ── ЧЕМ ЭТО ТЁМНОЕ ───────────────────────────────────────────────
//  Не «грустное» (минор — это ещё не тьма), а именно тёмное:
//   1. ЛАД. C фригийский: b2 (db) — главная нота трека. Это она делает
//      музыку тревожной, а не печальной. Она есть в пэде первого такта,
//      в мелодии как b9 и в басу как ход c2 → db2 → c2 (I–bII–I) —
//      самый узнаваемый жест лада.
//   2. НИЗ. Всё живёт в c1…c3. Мелодия уходит вверх только чтобы
//      прозвучать как одиночная точка, а не как линия.
//   3. МАЛАЯ НОНА (b9) вместо 9-й. В 05 девятка была краской, здесь
//      её место занимает b9 — тот же интервал, но на полутон ниже,
//      и он звучит как тревога, а не как джаз.
//   4. КВАРТЫ И СЕКУНДЫ. Режим 0 — квартовые стеки без терций вообще:
//      ни мажора, ни минора, ни центра. Режим 1 — минорные септаккорды
//      без квинты (Cm7, Fm7, Ebm7…), а там, где минор невозможен без
//      запрещённой ноты (db), — квинта плюс 9-я. Каденций нет: аккорд
//      меняется, а «домой» никто не приходит.
//   5. РАЗРЕШЕНИЯ НЕТ. Корни заканчиваются на g, а не на c. Фраза,
//      которая не пришла домой, и есть тревога.
//   6. ШУМ. Румбл на весь такт, винил, свип — тьма живёт в воздухе,
//      а не в нотах.
//
//  ── ДИССОНАНС: НАМЕРЕННЫЙ vs СЛУЧАЙНЫЙ ──────────────────────────
//  Тритон в дарк-техно — приём, а не ошибка. Но только там, где он стоит
//  осознанно и повторяется. Здесь их два, и оба в первом такте:
//    • стаб играет gb над c — «дьявольский» интервал, четверть, раз в 8 тактов;
//    • орган держит g3 против db4 пэда — это C7b9 без терции, целый такт.
//  Всё остальное чисто НАМЕРЕННО: у фраз длиной 7, 5 и 12 тактов тритон
//  всплывал бы каждый цикл в новом месте — это уже не тьма, а грязь.
//  Поэтому маркер `// @dark` разрешает тритоны только якорным фразам
//  (длина кратна 8), а tools/tension.mjs показывает их отдельным списком.
//
//  ── ГАРМОНИЯ: ОДНА СЕТКА, ДВЕ УКЛАДКИ ───────────────────────────
//  Корни 8 тактов, одни и те же в обоих режимах:
//      c  db  f  ab  eb  bb  db  g
//  Оба режима — C фригийский (c db eb f g ab bb) плюс хроматика как
//  краска. Разница только в укладке:
//    0 — КЛАСТЕРЫ: корень + кварта + (септима или b9). На такте ab ещё
//        и малая секунда. Терций нет — аккорд не мажор и не минор,
//        он просто стена.
//    1 — МИНОРНЫЕ СЕПТАККОРДЫ БЕЗ КВИНТЫ: Cm7, Fm7, Ebm7, Bbm7, Gm7;
//        на db — квинта + 9-я (минорная терция там запрещена, см. ниже).
//        Терция есть, но только малая; септима не даёт «доминанты»,
//        поэтому никуда не тянет.
//  Переключение — на границе 8 тактов (seg), начатая фраза доигрывается.
//
//  ── ЧТО ПЕРЕКЛЮЧАЕТСЯ, А ЧТО НЕТ ────────────────────────────────
//  Переключаются: pad, stab, мелодия (MEL_A / MEL_B).
//  Играют в обоих режимах: орган (корень+квинта), общая мелодия MEL,
//  арпеджио, бас, бульки. Иначе переключение звучало бы как смена трека.
//
//  ── УДАРНЫЕ: ЧЕТЫРЕ РЕЖИМА (как в 06) ───────────────────────────
//    0 — даб: хэты на «и», пусто, бочка четыре в пол.
//    1 — прямо: 16-е хэты с акцентами.
//    2 — лом: синкопы, бочка на 2 и 4, пусто на 1 и 3.
//    3 — брейк: бочка 1 / 3 / «а» третьей, снейр на 3, призраки,
//        филл 32-ми по снейру раз в 4 такта.
//
//  ── ПОЧЕМУ НЕ НАДОЕДАЕТ ─────────────────────────────────────────
//  Длины фраз не совпадают: воздух 16, крошка 12, бас-призрак 12,
//  мелодия A 7, бульки 5, перкуссия 5, блипы 3, остальное 8. Общий
//  цикл — тысячи тактов. Плюс рандом: sometimesBy на хэтах и мелодии,
//  degradeBy на блипах, `|` на металле, pan по rand.
//
//  ── СТАРТ ───────────────────────────────────────────────────────
//  Звучит сразу только атмосфера: воздух 0.14, дрон 0.12, винил 0.05,
//  пэд 0.08. Остальное в нуле — поднимаешь по одной.
// ══════════════════════════════════════════════════════════════════

