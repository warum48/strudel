// m() обязателен: строка в переменной без m() в браузере не парсится
// и превращается в одну «ноту» из всего текста, то есть в тишину.
const phrase = (bars) => m('<' + bars.join(' ') + '>')

// Корни на 8 тактов: c db f ab eb bb db g. Заканчиваются на g, а не на c:
// фраза, которая не пришла домой, и есть тревога.
// Строка ниже — машинный маркер для tools/tension.mjs (проверка на тритоны).
// @roots c db f ab eb bb db g
// @dark — тритоны в ЯКОРНЫХ фразах (8 тактов) считаются намеренными:
// в дарк-техно это приём, а не ошибка. У дрейфующих фраз (7/5/12) тритон
// по-прежнему запрещён — там он всплывает в случайном месте каждый цикл.
//
// ПОЧЕМУ УКЛАДКИ ИМЕННО ТАКИЕ. Часть фраз дрейфует против гармонии
// (7, 5 и 12 тактов против 8), то есть любая их нота может попасть на любой
// корень. Значит эти ноты должны быть чистыми над ВСЕМ набором корней, а
// пэд не имеет права содержать ноту, которая даёт им тритон. Отсюда рабочее
// множество нот: c, db, eb, f, g, ab, bb — то есть C фригийский. Из него
// выброшены ровно те, что стреляют: gb (тритон к c), a (к eb), b (к f),
// d (к ab), e (к bb). Первая версия пэдов была богаче — и дала 634 места
// трения, потому что gb в пэде стрелял в каждую ноту c у дрейфующих фраз.
// gb при этом НЕ исчез из трека: он живёт в металле и в стабе ниже, где
// стоит осознанно и повторяется.
const PAD_A = phrase([
  '[c3,f3,db4]',        // c:   кварта + b9 — кластер, ни мажора, ни минора
  '[db3,ab3,eb4]',      // db:  квинты — b9 (d) тут запрещена, она тритон к ab
  '[f3,bb3,eb4]',       // f:   кварты
  '[ab3,db4,eb4]',      // ab:  кварта + малая секунда — вот она, тьма
  '[eb3,ab3,bb3]',      // eb:  кварта + большая секунда
  '[bb3,f4,ab4]',       // bb:  квинта + малая терция
  '[db3,ab3,eb4]',      // db
  '[g3,c4,f4]',         // g:   кварты
])

// Режим 1: минорные септаккорды на тех же корнях, БЕЗ квинты — так в укладку
// не попадают gb/a/b/d/e, которые запрещены выше. Терция есть, но только
// малая; септима не даёт доминанты, поэтому аккорд меняется, а «домой»
// никто не приходит.
const PAD_B = phrase([
  '[c3,eb3,bb3,db4]',   // Cm7 + b9: фригийская краска прямо в минорном режиме
  '[db3,ab3,eb4]',      // Db: квинта + 9-я (минора тут не выйдет — e запрещён)
  '[f3,ab3,eb4]',       // Fm7 без квинты
  '[ab3,db4,eb4]',      // Ab: кварта + малая секунда
  '[eb3,g3,bb3]',       // Ebm7 без квинты
  '[bb3,db4,f4]',       // Bbm7 без квинты
  '[db3,ab3,eb4]',      // Db
  '[g3,bb3,f4]',        // Gm7 без квинты
])

// Орган: только корень + квинта — поэтому годится в оба режима.
