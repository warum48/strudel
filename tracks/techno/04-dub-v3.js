//  ЧТО КРУТИТЬ ВО ВРЕМЯ ИГРЫ
//
//  старт:        пэд + воздух. Дальше stabVol 0.5 → kickVol 0.5 →
//                hatVol 0.25 → bassVol 0.6 + subVol 0.5 → bubbleVol 0.3
//  середина:     harmony 1 — пэд и стаб уходят в джаз. Защёлка сработает
//                на границе 8-тактовой фразы, начатая арза доиграется.
//                Для «выхода из вакханалии»: mode 1, masterCut 3000,
//                bubbleVol 0.1, bassGrit 0, verb 0.8 — станет тихо и тепло.
//  обратно:      harmony 0, mode 0, masterCut 9000, bassGrit 0.35
//  режимы:       mode 0 даб / 1 прямо / 2 лом — переключается на лету,
//                бочка остаётся, гармония не меняется
//  реверб:       verb 0.65 уже мокро. 0.9 + verbSize 16 = собор,
//                0.15 — сухая комната. Главная ручка этого трека.
//  стаб:         stabDelay 0.7 + stabFb 0.75 — хвост уезжает на 8 тактов
//                stabCut 400 — глухо из-под воды, 4000 — щёлкает
//  бульки:       bubbleFb 0.8 + bubbleEcho 0.7 — пузыри уползают
//                bubbleJump 0.8 — почти всё на октаву выше (стекло)
//  бас:          bassGrit 0 — чистый, 0.9 — почти каждая нота шершавая
//                bassCrush 2 + bassDist 0.7 — рвёт динамик
//  пэд:          padCut 300 + padLfo 6 — аккорд плавает под водой
//                padAtk 3 — вплывает медленно, 0.02 — аккорд-удар
//  пустота:      всё вниз, кроме noiseVol 0.2 + verb 0.9
//
//  Хочешь 909 — .bank('RolandTR909') к бочке, хэтам и клэпу.
