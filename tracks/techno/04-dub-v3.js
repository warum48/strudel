// ══════════════════════════════════════════════════════════════════
//  TECHNO DUB 04 (v3)  ·  Strudel  ·  124 BPM
//
//  Версия 03 + одна вещь, и она не про музыку: ШИРИНА СЛАЙДЕРОВ.
//  Виджет strudel.cc рисует себя 64px инлайном — мышкой в шаг 0.01
//  не попасть, а промах на 0.05 слышно. Здесь 180px: проверено, что
//  вёрстка не едет (scrollWidth не растёт), а дальше ~200px строки
//  начинают лезть вправо. Правило с !important перебивает инлайн.
//
//  Всё остальное — байт в байт как в 03: те же дорожки, те же режимы,
//  та же защёлка гармонии. Музыка не тронута.
//
//  ── что было в 03 (v2) ────────────────────────────────────────────
//   1. РЕЖИМ УДАРНЫХ — слайдер-«кнопка» на 3 положения (0 даб / 1 прямо /
//      2 лом). Бочка не меняется ни в одном режиме, она якорь.
//   2. МИКШЕР ВЫНЕСЕН НАВЕРХ: сначала только громкости всех инструментов,
//      следующим блоком — их настройки (срезы, огибающие, дилеи).
//   3. ГАРМОНИЯ: переключатель атонал ⇄ джаз. В джазовом режиме пэд играет
//      аккорды с 9-ми и 11-ми ступенями — тепло, сложно, но без доминанты,
//      поэтому «приятно», а не «сопливо». Переключение защёлкивается на
//      границе 8-тактовой фразы: начатая арза доигрывается целиком.
//
//  Как это сделано с защёлкой: `harmony.seg(1/8)` — сигнал, который
//  сэмплируется один раз в 8 тактов. Двинул слайдер — значение подхватится
//  только на следующей границе фразы. Плюс gain читается в момент удара,
//  поэтому уже звучащий аккорд доигрывает в любом случае, даже если
//  переключение придёт в его середину.
//
//  Почему ничего не наезжает (как в 02, проверено `npm run doubles`):
//   один сэмпл = одна дорожка; вместо every() — lastOf(4, …); дилей 0.4375.
// ══════════════════════════════════════════════════════════════════

const BPM = 124
setcpm(BPM / 4) // один цикл = один такт 4/4 (≈ 1.935 с)

// ══════════════════════════════════════════════════════════════════
//  ШИРИНА СЛАЙДЕРОВ
// ══════════════════════════════════════════════════════════════════
// Ширина ставится виджетом инлайном (`width:64px`) без !important, поэтому
// правило с !important её перебивает. 180 — проверенный максимум, после
// которого строки со слайдерами начинают вылезать вправо.
//
// ⚠ строки ТОЛЬКО в одинарных кавычках: транспайлер REPL оборачивает в m()
//   всё, что в двойных и в бэктиках, — CSS-правило превратилось бы в паттерн.
const SLIDER_PX = 180
if (typeof document !== 'undefined' && !document.getElementById('slider-w')) {
  const st = document.createElement('style')
  st.id = 'slider-w'
  st.textContent = '.cm-slider input { width: ' + SLIDER_PX + 'px !important; }'
  document.head.appendChild(st)
}

// ══════════════════════════════════════════════════════════════════
//  ПЕРЕКЛЮЧАТЕЛИ
// ══════════════════════════════════════════════════════════════════

// РЕЖИМ УДАРНЫХ. Кнопок в Strudel нет, поэтому слайдер с шагом 1.
//   0 — даб:    хэты на «и», перкуссия редко, клики сыпятся
//   1 — прямо:  ровные шестнадцатые, перкуссия на 2 и 4, клики редко
//   2 — лом:    синкопы, перкуссия сбита, клики часто
const mode = slider(0, 0, 2, 1)
const m0 = mode.fmap((m) => (m === 0 ? 1 : 0))
const m1 = mode.fmap((m) => (m === 1 ? 1 : 0))
const m2 = mode.fmap((m) => (m === 2 ? 1 : 0))

// ГАРМОНИЯ. 0 — атональность (квартовые аккорды), 1 — джаз (9-е и 11-е).
// seg(1/8) = защёлка на 8 тактов: фраза пэда всегда доигрывается.
const harmony = slider(0, 0, 1, 1)
const hQ = harmony.seg(1 / 8)
const hAtonal = hQ.fmap((h) => (h < 0.5 ? 1 : 0))
const hJazz = hQ.fmap((h) => (h < 0.5 ? 0 : 1))

// ══════════════════════════════════════════════════════════════════
//  МИКШЕР — только громкости, ничего больше
// ══════════════════════════════════════════════════════════════════

const kickVol   = slider(0, 0, 1.4, 0.01) // бочка
const hatVol    = slider(0, 0, 1, 0.01)   // хэты
const percVol   = slider(0, 0, 0.9, 0.01) // перкуссия
const clickVol  = slider(0, 0, 0.8, 0.01) // клики/глитчи
const noiseVol  = slider(0.12, 0, 0.5, 0.01) // воздух (звучит сразу)
const stabVol   = slider(0, 0, 1.2, 0.01) // стаб
const padVol    = slider(0.16, 0, 0.8, 0.01) // пэд (звучит сразу)
const bubbleVol = slider(0, 0, 0.8, 0.01) // бульки
const bassVol   = slider(0, 0, 1.4, 0.01) // бас, пила
const subVol    = slider(0, 0, 1, 0.01)   // бас, синус на октаву ниже
const melVol    = slider(0, 0, 1, 0.01)   // мелодия

// ОБЩЕЕ: пространство и сайдчейн — это не инструменты, но и не настройки
const verb     = slider(0.65, 0, 1, 0.01)  // общий реверб — главная ручка
const verbSize = slider(9, 1, 20, 0.5)     // размер комнаты
const duck     = slider(0.45, 0, 1, 0.01)  // сайдчейн баса от бочки

// ══════════════════════════════════════════════════════════════════
//  НАСТРОЙКИ ИНСТРУМЕНТОВ
// ══════════════════════════════════════════════════════════════════

// ВЕРХ (хэты, перкуссия, клики)
const masterCut = slider(9000, 200, 16000, 100) // срез верха, Гц
const masterRes = slider(3, 0, 20, 0.5)         // резонанс на срезе
const masterHpf = slider(120, 20, 2000, 10)     // хайпасс верха (билд-ап)

// БОЧКА — глухая: срез низкий, жёсткость средняя
const kickCut   = slider(1800, 500, 16000, 100)
const kickShape = slider(0.45, 0, 0.95, 0.01)

// ХЭТЫ
const hatCut  = slider(7000, 500, 16000, 100)
const hatRoll = slider(0.2, 0, 1, 0.01) // шанс дроби на хэте

// ПЕРКУССИЯ
const percEcho = slider(0.4, 0, 0.9, 0.01)
const percFb   = slider(0.5, 0, 0.9, 0.01)

// КЛИКИ
const clickCut   = slider(6000, 300, 16000, 100)
const clickCrush = slider(4, 1, 16, 0.5)
const clickRate  = slider(0.35, 0, 0.95, 0.01) // сколько кликов выкинуть
const clickStut  = slider(0.25, 0, 1, 0.01)    // шанс глитч-стута

// ВОЗДУХ
const noiseCut = slider(700, 100, 8000, 20)
const noiseLfo = slider(2.5, 0, 10, 0.5)

// ПЭД — общий для атонального и джазового: разный только тембр и аккорды
const padCut    = slider(900, 120, 6000, 20)
const padReso   = slider(4, 0, 20, 0.5)
const padLfo    = slider(1.5, 0, 8, 0.1)        // дыхание среза, октавы
const padLfoR   = slider(0.125, 0.03, 1, 0.005) // скорость: 0.125 = раз в 8 тактов
const padChorus = slider(0.5, 0, 1, 0.01)
const padDetune = slider(0.1, 0, 0.5, 0.01)
const padAtk    = slider(0.9, 0.02, 4, 0.02) // 0.9 = вплывает, 0.02 = щипок

// СТАБ
const stabCut   = slider(1200, 150, 8000, 20)
const stabReso  = slider(6, 0, 24, 0.5)
const stabDecay = slider(0.22, 0.03, 1.2, 0.01)
const stabDelay = slider(0.5, 0, 0.9, 0.01)
const stabFb    = slider(0.55, 0, 0.9, 0.01)

// БУЛЬКИ
const bubbleCut    = slider(3000, 200, 9000, 20)
const bubbleReso   = slider(8, 0, 24, 0.5)
const bubbleEcho   = slider(0.5, 0, 0.9, 0.01)
const bubbleFb     = slider(0.55, 0, 0.9, 0.01)
const bubbleSparse = slider(0.15, 0, 0.9, 0.01)
const bubbleJump   = slider(0.35, 0, 1, 0.01)

// БАС
const bassCut   = slider(220, 60, 2000, 10)
const bassReso  = slider(9, 0, 26, 0.5)
const bassEnv   = slider(3.5, 0, 8, 0.1)
const bassGrit  = slider(0.35, 0, 1, 0.01) // шанс, что нота шершавая
const bassCrush = slider(5, 1, 16, 0.5)    // 1 = злой биткраш, 16 = почти чисто
const bassDist  = slider(0.4, 0, 0.95, 0.01)
const bassRand  = slider(0.2, 0, 0.6, 0.01)
const bassLfo   = slider(1.5, 0, 10, 0.5)
const bassLfoR  = slider(1, 0.25, 8, 0.25)

// МЕЛОДИЯ
const melCut  = slider(2400, 200, 9000, 20)
const melFm   = slider(2.6, 0, 8, 0.1)
const melFmh  = slider(3.41, 0.5, 8, 0.01) // нецелая гармоничность = холод
const melEcho = slider(0.5, 0, 0.9, 0.01)
const melFb   = slider(0.5, 0, 0.9, 0.01)
const melPan  = slider(0.5, 0, 1, 0.01)

// 1 ± amt на каждое событие: фильтр не повторяется от прохода к проходу
const jit = (amt) => rand.mul(2).sub(1).mul(amt).add(1)

// Склейка списка тактов в одну фразу: <бар1 бар2 …> — по такту на элемент.
// m() обязателен: транспайлер REPL оборачивает в m() только строковые
// литералы, а строку в переменной не видит — note(BASS) получил бы одну
// «ноту» из всего текста фразы, то есть тишину.
const phrase = (bars) => m('<' + bars.join(' ') + '>')

// ══════════════════════════════════════════════════════════════════
//  ПЭД — два режима, один голос
// ══════════════════════════════════════════════════════════════════

// АТОНАЛЬНЫЙ: квартовые аккорды (только чистые кварты), корень ползёт
// хроматически d → eb → f → gb → g → ab → a → bb. Кварта не говорит
// «тоника» или «доминанта», поэтому аккорд висит и не разрешается.
const PAD_ATONAL = phrase([
  '[d3,g3,c4,f4]',
  '[eb3,ab3,db4,gb4]',
  '[f3,bb3,eb4,ab4]',
  '[gb3,b3,e4,a4]',
  '[g3,c4,f4,bb4]',
  '[ab3,db4,gb4,c5]',
  '[a3,d4,g4,c5]',
  '[bb3,eb4,ab4,db5]',
])

// ДЖАЗОВЫЙ: те же 8 тактов, но аккорды с 9-ми и 11-ми ступенями —
// Cmaj9 → Am9 → Fmaj9 → Dm11 → Bbmaj9 → Gm9 → Ebmaj9 → Dbmaj9.
// Ни одного доминантсептаккорда, поэтому гармония сложная, но никуда
// не тянет и не «разрешается» — можно сидеть в ней бесконечно.
// Бас при этом держит педаль на c, и все эти аккорды над ней ложатся.
const PAD_JAZZ = phrase([
  '[c3,e3,b3,d4]',   // Cmaj9
  '[a2,c3,g3,b3]',   // Am9
  '[f2,a2,c3,g3]',   // Fmaj9
  '[d3,f3,c4,e4]',   // Dm11
  '[bb2,d3,a3,c4]',  // Bbmaj9
  '[g2,bb2,f3,a3]',  // Gm9
  '[eb3,g3,d4,f4]',  // Ebmaj9
  '[db3,f3,ab3,eb4]', // Dbmaj9
])

// Атональный пэд: суперпила, широко, холодно
$: note(PAD_ATONAL)
  .s("supersaw").unison(4).detune(padDetune)
  .lpf(padCut).lpq(padReso).ftype("24db")
  .lpdepth(padLfo).lpsync(padLfoR) // срез дышит сам
  .chorus(padChorus)
  .attack(padAtk).decay(1.5).sustain(0.9).release(2.4)
  .room(verb).roomsize(verbSize)
  .gain(padVol.mul(hAtonal))

// Джазовый пэд: обычная пила, теплее и уже — тот же голос, другое лицо
$: note(PAD_JAZZ)
  .s("sawtooth").unison(2).detune(padDetune)
  .lpf(padCut).lpq(padReso).ftype("24db")
  .lpdepth(padLfo).lpsync(padLfoR)
  .chorus(padChorus)
  .attack(padAtk).decay(1.5).sustain(0.9).release(2.4)
  .room(verb).roomsize(verbSize)
  .gain(padVol.mul(hJazz))

// ──────────────────────────────────────────────────────────────────
//  ВОЗДУХ — ровный шум, один вдох на 16 тактов
// ──────────────────────────────────────────────────────────────────

$: s("white")
  .gain(noiseVol)
  .lpf(noiseCut).lpq(0.5)
  .lpdepth(noiseLfo).lpsync(0.0625)
  .room(verb).roomsize(verbSize)

// ──────────────────────────────────────────────────────────────────
//  БОЧКА — единственная дорожка с сэмплом bd, ни от чего не зависит
// ──────────────────────────────────────────────────────────────────

$: s("bd*4")
  .gain(kickVol)
  .shape(kickShape)
  .lpf(kickCut)
  .duckorbit(2).duckdepth(duck).duckattack(0.05) // дакает бас (orbit 2)

// ──────────────────────────────────────────────────────────────────
//  СТАБ — сердце даб-техно: короткий удар, длинный хвост
// ──────────────────────────────────────────────────────────────────

const STAB_ATONAL = phrase([
  '[~ [d4,g4,c5,f5] ~ [d4,g4,c5,f5]]',
  '[~ [eb4,ab4,db5,gb5] ~ [eb4,ab4,db5,gb5]]',
  '[~ [f4,bb4,eb5,ab5] ~ [f4,bb4,eb5,ab5]]',
  '[~ [gb4,b4,e5,a5] ~ [gb4,b4,e5,a5]]',
])

const STAB_JAZZ = phrase([
  '[~ [c4,e4,g4,b4] ~ [c4,e4,g4,b4]]', // Cmaj7: девятку (d) держит пэд,
                                        // а не стаб — иначе d5 дублируется
                                        // с мелодией в той же позиции
  '[~ [a3,c4,g4,b4] ~ [a3,c4,g4,b4]]',
  '[~ [f3,a3,c4,g4] ~ [f3,a3,c4,g4]]',
  '[~ [d4,f4,c5,e5] ~ [d4,f4,c5,e5]]',
  '[~ [bb3,d4,a4,c5] ~ [bb3,d4,a4,c5]]',
  '[~ [g3,bb3,f4,a4] ~ [g3,bb3,f4,a4]]',
  '[~ [eb4,g4,d5,f5] ~ [eb4,g4,d5,f5]]',
  '[~ [db4,f4,ab4,eb5] ~ [db4,f4,ab4,eb5]]',
])

// Атональный стаб: треугольник с формантой, гласная плывёт a → e → o → u
$: note(STAB_ATONAL)
  .s("triangle")
  .vowel("<a e o u>") // форманта: аккорд «говорит»
  .lpf(stabCut).lpq(stabReso).ftype("24db")
  .decay(stabDecay).sustain(0).release(0.14)
  .delay(stabDelay).delaytime(0.4375).delayfeedback(stabFb)
  .room(verb).roomsize(verbSize)
  .gain(stabVol.mul(hAtonal))

// Джазовый стаб: квадрат, гласные мягче (u → o → a → e) — звучит как
// электрическое пиано, а не как сигнал
$: note(STAB_JAZZ)
  .s("square")
  .vowel("<u o a e>")
  .lpf(stabCut).lpq(stabReso).ftype("24db")
  .decay(stabDecay).sustain(0).release(0.14)
  .delay(stabDelay).delaytime(0.4375).delayfeedback(stabFb)
  .room(verb).roomsize(verbSize)
  .gain(stabVol.mul(hJazz))

// ──────────────────────────────────────────────────────────────────
//  БУЛЬКИ
//  5 тактов. Бульк = короткий синус, внутри которого высота падает:
//  [g5@0.25 g4@0.75] — четверть слота наверху, три четверти внизу.
// ──────────────────────────────────────────────────────────────────

const BUB = phrase([
  '[~ ~ [g5@0.25 g4@0.75] ~ ~ ~ ~ ~]',
  '[~ [d5@0.2 d4@0.8] ~ ~ ~ ~ ~ ~]',
  '[~ ~ ~ [bb5@0.3 bb4@0.7] ~ ~ ~ ~]',
  '[~ ~ ~ ~ [eb5@0.2 eb4@0.8] ~ ~ ~]',
  '[~ [f#5@0.25 f#4@0.75] ~ ~ ~ ~ [c5@0.2 c4@0.8] ~]',
])

$: note(BUB)
  .s("sine")
  .decay(0.09).sustain(0).release(0.04)
  .lpf(bubbleCut).lpq(bubbleReso)
  .sometimesBy(bubbleJump, (x) => x.add(note("12"))) // случайная октава
  .degradeBy(bubbleSparse) // случайные пропуски
  .delay(bubbleEcho).delaytime(0.4375).delayfeedback(bubbleFb)
  .pan(rand.mul(1.6).sub(0.8))
  .room(verb).roomsize(verbSize)
  .gain(bubbleVol)

// ──────────────────────────────────────────────────────────────────
//  БАС
//  8 тактов, длинная нота на «и». Цвета: тритон f#, малая секунда db,
//  малая терция eb, малая секста ab — в джазовом режиме они работают
//  как альтерации над педалью c, поэтому конфликта нет.
//  Шершавость — тембром (crush + distort), а не ритмом: ноты не двоятся.
// ──────────────────────────────────────────────────────────────────

const BASS = phrase([
  '[~ ~ c2@1.5 ~@0.5]',
  '[~ ~ c2@1.5 ~@0.5]',
  '[~ ~ c2@1.5 f#2@0.5]',
  '[~ ~ db2@0.5 c2@1.5]',
  '[~ ~ c2@1.5 ~@0.5]',
  '[~ ~ eb2@1.5 ~@0.5]',
  '[~ ~ ab2@1 c2@1]',
  '[~ ~ c2@1 f#2@0.5 db2@0.5]',
])

$: stack(
     note(BASS).s("sawtooth").gain(bassVol), // то, что слышно
     note(BASS).add(note("-12")).s("sine").gain(subVol), // то, что чувствуется
   )
  .lpf(bassCut).lpq(bassReso).ftype("24db")
  .lpenv(bassEnv.mul(jit(bassRand)))
  .lpa(0.004).lpd(0.12).lpsustain(0.45)
  .lpdepth(bassLfo.mul(jit(bassRand))).lpsync(bassLfoR).lpdc(0)
  .sometimesBy(bassGrit, (x) => x.crush(bassCrush).distort(bassDist))
  .attack(0.003).decay(0.3).sustain(0.5).release(0.08)
  .orbit(2)

// ──────────────────────────────────────────────────────────────────
//  МЕЛОДИЯ — 7 тактов, редкая. Девятые, тритон, малая секста.
// ──────────────────────────────────────────────────────────────────

const MEL = phrase([
  '[~ ~ d5 ~ ~ ~ ~ ~]',
  '[~ ~ ~ db5 ~ ~ ~ ~]',
  '[~ f#5 ~ ~ ~ ~ ~ ~]',
  '[~ ~ ~ ~ eb5 ~ ~ ~]',
  '[d5 ~ ~ ~ ~ ~ ~ ~]',
  '[~ ~ ~ ~ ~ ab4 ~ d5]',
  '[~ ~ db5 ~ ~ f#5 ~ ~]',
])

$: note(MEL)
  .s("square")
  .fm(melFm).fmh(melFmh)
  .decay(0.18).sustain(0).release(0.06)
  .lpf(melCut).lpq(4)
  .delay(melEcho).delaytime(0.375).delayfeedback(melFb)
  .room(verb).roomsize(verbSize)
  .pan(melPan.mul("<1 -1>")) // пинг-понг
  .gain(melVol)

// ══════════════════════════════════════════════════════════════════
//  УДАРНЫЕ В ТРЁХ РЕЖИМАХ  (mode 0 / 1 / 2)
//  Каждый режим — отдельный слой, звучит ровно один: гейн остальных = 0.
//  Дробь на 4-м такте через lastOf, а не every — every стреляет на нулевом.
// ══════════════════════════════════════════════════════════════════

// ХЭТЫ
$: stack(
     s("~ hh ~ hh ~ hh ~ hh").gain(hatVol.mul(m0)),                    // 0 даб: на «и»
     s("hh*16").gain(hatVol.mul("[.35 .12 .22 .12]*4").mul(m1)),       // 1 прямо: 16-е тихо
     s("hh ~ ~ hh ~ hh ~ ~").gain(hatVol.mul(m2)),                     // 2 лом: синкопы
   )
  .lpf(hatCut).hpf(masterHpf)
  .sometimesBy(hatRoll, (x) => x.ply(2))
  .lastOf(4, (x) => x.ply(2))

// ПЕРКУССИЯ — 3 такта в режиме 0, поэтому не совпадает ни с басом (8),
// ни с мелодией (7), ни с бульками (5)
const PERC_DUB = phrase([
  '[~ ~ rim ~ ~ ~ ~ ~]',
  '[~ rim ~ ~ ~ ~ ~ ~]',
  '[~ ~ ~ rim ~ ~ ~ ~]',
])

$: stack(
     s(PERC_DUB).gain(percVol.mul(m0)),           // 0 даб: редко, вразнобой
     s("~ ~ rim ~ ~ ~ rim ~").gain(percVol.mul(m1)), // 1 прямо: 2 и 4
     s("rim ~ ~ ~ ~ rim rim ~").gain(percVol.mul(m2)), // 2 лом: сбито
   )
  .delay(percEcho).delaytime(0.4375).delayfeedback(percFb)
  .pan("<.55 .35 .7>")
  .lpf(masterCut).lpq(masterRes).hpf(masterHpf)

// КЛИКИ И ГЛИТЧИ — раздавленный клэп
// стутер, который НЕ затирает громкость: stut() внутри делает
// pat.gain(pow(feedback, i)), и первая копия всегда играет на 1.0 мимо
// clickVol — слой не глушится. Здесь тот же ритм, но gain умножается.
const stutGain = (times, fb, step) => (x) =>
  x.echoWith(times, step, (p, i) =>
    p.withValue((v) => ({ ...v, gain: (v.gain ?? 1) * Math.pow(fb, i) })),
  )

$: stack(
     s("cp ~ ~ cp ~ ~ cp ~").gain(clickVol.mul(m0)),
     s("cp ~ ~ ~ ~ cp ~ ~").gain(clickVol.mul(m1).mul(0.7)),
     s("cp ~ cp cp ~ cp ~ cp").gain(clickVol.mul(m2)),
   )
  .crush(clickCrush)
  .decay(0.02).sustain(0)
  .degradeBy(clickRate)
  .sometimesBy(clickStut, stutGain(4, 0.55, 0.03125))
  .pan(rand.mul(1.6).sub(0.8))
  .lpf(clickCut).lpq(4)
  .room(verb).roomsize(verbSize)

