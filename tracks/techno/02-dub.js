// ══════════════════════════════════════════════════════════════════
//  TECHNO DUB 02  ·  Strudel  ·  124 BPM
//
//  Дуб-техно: тот же Берлин, но медленнее, глубже и мокрее. Главный
//  инструмент — не бочка, а пространство: реверб 0.65 + roomsize 9 и
//  дилей с обратной связью на стабе, бульках, перкуссии и кликах.
//
//  Старт — атмосфера, а не ритм. По умолчанию звучат только пэд (0.16)
//  и воздух (0.12); бочка, бас, стаб, мелодия и всё остальное на 0.
//  Дальше поднимаешь сам, в любом порядке.
//
//  Гармония. Никаких трезвучий и никакого тонального центра: пэд — это
//  квартовые аккорды (только чистые кварты), у которых корень ползёт
//  вверх хроматически d → eb → f → gb → g → ab → a → bb. Кварта не
//  говорит «тоника» или «доминанта», поэтому аккорд висит и никуда не
//  разрешается. Стаб играет те же кварты выше, мелодия живёт на
//  девятых, тритоне и малых секундах. Джазово по интервалам, холодно
//  по смыслу.
//
//  Почему тут ничего не наезжает друг на друга (в 01-berlin наезжало):
//   1. Каждый сэмпл принадлежит РОВНО одной дорожке. bd — только бочка
//      (в 01 было две: бочка + румбл, обе s("bd") в одних и тех же
//      позициях — при поднятом rumbleVol это буквально второй кик).
//   2. Ни одного every(n, …) — он срабатывает на НУЛЕВОМ такте, поэтому
//      в 01 первый же такт шёл 32-ми хэтами (74 события вместо 40).
//      Здесь дробление только через lastOf(4, …) — на 4-м такте.
//   3. sometimesBy не удваивает ноты (ply), а меняет ТЕМБР (crush +
//      distort). В 01 sometimesBy(bassGhost, ply(2)) дублировал первую
//      ноту баса, потому что rand в момент старта = 0.
//   4. Дилей стоит на 0.4375 такта (7/16), а не на 0.375 (6/16): хвост
//      попадает между ударами, а не поверх следующего удара.
//
//  Длины фраз нарочно не сходятся:
//      пэд        8 тактов
//      бас        8 тактов
//      мелодия    7 тактов
//      стаб       4 такта
//      бульки     5 тактов
//      перкуссия  3 такта
//  Общий цикл — 840 тактов, то есть трек не повторяется.
// ══════════════════════════════════════════════════════════════════

const BPM = 124
setcpm(BPM / 4) // один цикл = один такт 4/4 (≈ 1.935 с)

// ──────────────────────────────────────────────────────────────────
//  ПУЛЬТ   slider(значение, минимум, максимум, шаг)
// ──────────────────────────────────────────────────────────────────

// МАСТЕР: общий реверб, сайдчейн и фильтр верха (хэты, перкуссия, клики)
const masterCut = slider(9000, 200, 16000, 100) // срез верха, Гц
const masterRes = slider(3, 0, 20, 0.5)         // резонанс на срезе
const masterHpf = slider(120, 20, 2000, 10)     // хайпасс верха (билд-ап)
const verb      = slider(0.65, 0, 1, 0.01)      // общий реверб — главная ручка
const verbSize  = slider(9, 1, 20, 0.5)         // размер комнаты
const duck      = slider(0.45, 0, 1, 0.01)      // сайдчейн баса от бочки

// ПЭД — то, с чего начинается трек. Квартовые аккорды, много воздуха.
const padVol    = slider(0.16, 0, 0.8, 0.01)    // громкость (звучит сразу)
const padCut    = slider(900, 120, 6000, 20)    // срез
const padReso   = slider(4, 0, 20, 0.5)         // резонанс
const padLfo    = slider(1.5, 0, 8, 0.1)        // дыхание среза, октавы
const padLfoR   = slider(0.125, 0.03, 1, 0.005) // скорость: 0.125 = раз в 8 тактов
const padChorus = slider(0.5, 0, 1, 0.01)       // ширина/плывучесть
const padDetune = slider(0.1, 0, 0.5, 0.01)     // расстройка унисона
const padAtk    = slider(0.9, 0.02, 4, 0.02)    // атака: 0.9 = вплывает, 0.02 = щипок

// ВОЗДУХ — ровный шум. Второе, что звучит сразу.
const noiseVol  = slider(0.12, 0, 0.5, 0.01)
const noiseCut  = slider(700, 100, 8000, 20)
const noiseLfo  = slider(2.5, 0, 10, 0.5)

// БОЧКА — по умолчанию 0. Глухая: срез низкий, жёсткость средняя.
const kickVol   = slider(0, 0, 1.4, 0.01)
const kickShape = slider(0.45, 0, 0.95, 0.01)
const kickCut   = slider(1800, 500, 16000, 100)

// СТАБ — аккорд-удар с вокальным фильтром и большим дилеем.
// Это и есть «дабовость»: короткий удар, длинный хвост.
const stabVol   = slider(0, 0, 1.2, 0.01)
const stabCut   = slider(1200, 150, 8000, 20)
const stabReso  = slider(6, 0, 24, 0.5)
const stabDecay = slider(0.22, 0.03, 1.2, 0.01)
const stabDelay = slider(0.5, 0, 0.9, 0.01)
const stabFb    = slider(0.55, 0, 0.9, 0.01)

// БУЛЬКИ — короткие синусы с падением высоты внутри ноты.
const bubbleVol    = slider(0, 0, 0.8, 0.01)
const bubbleCut    = slider(3000, 200, 9000, 20)
const bubbleReso   = slider(8, 0, 24, 0.5)
const bubbleEcho   = slider(0.5, 0, 0.9, 0.01)
const bubbleFb     = slider(0.55, 0, 0.9, 0.01)
const bubbleSparse = slider(0.15, 0, 0.9, 0.01) // сколько бульков выкинуть
const bubbleJump   = slider(0.35, 0, 1, 0.01)   // шанс прыжка на октаву

// БАС — два слоя (пила + синус на октаву ниже) и «шершавость» на иногда.
const bassVol   = slider(0, 0, 1.4, 0.01)
const subVol    = slider(0, 0, 1, 0.01)
const bassCut   = slider(220, 60, 2000, 10)
const bassReso  = slider(9, 0, 26, 0.5)
const bassEnv   = slider(3.5, 0, 8, 0.1)
const bassGrit  = slider(0.35, 0, 1, 0.01)  // шанс, что нота шершавая
const bassCrush = slider(5, 1, 16, 0.5)     // 1 = злой биткраш, 16 = почти чисто
const bassDist  = slider(0.4, 0, 0.95, 0.01)
const bassRand  = slider(0.2, 0, 0.6, 0.01)
const bassLfo   = slider(1.5, 0, 10, 0.5)
const bassLfoR  = slider(1, 0.25, 8, 0.25)

// МЕЛОДИЯ — редкая, металлическая, без разрешений.
const melVol  = slider(0, 0, 1, 0.01)
const melCut  = slider(2400, 200, 9000, 20)
const melFm   = slider(2.6, 0, 8, 0.1)
const melFmh  = slider(3.41, 0.5, 8, 0.01) // нецелая гармоничность = холод
const melEcho = slider(0.5, 0, 0.9, 0.01)
const melFb   = slider(0.5, 0, 0.9, 0.01)
const melPan  = slider(0.5, 0, 1, 0.01)

// БАРАБАНЫ
const hatVol   = slider(0, 0, 1, 0.01)
const hatRoll  = slider(0.2, 0, 1, 0.01) // шанс дроби на хэте
const hatCut   = slider(7000, 500, 16000, 100)
const percVol  = slider(0, 0, 0.9, 0.01)
const percEcho = slider(0.4, 0, 0.9, 0.01)
const percFb   = slider(0.5, 0, 0.9, 0.01)

// КЛИКИ/ГЛИТЧИ — редкие, раздавленные биткрашем, с рваными стутами.
const clickVol   = slider(0, 0, 0.8, 0.01)
const clickCut   = slider(6000, 300, 16000, 100)
const clickCrush = slider(4, 1, 16, 0.5)
const clickRate  = slider(0.35, 0, 0.95, 0.01) // сколько кликов выкинуть
const clickStut  = slider(0.25, 0, 1, 0.01)    // шанс глитч-стута

// 1 ± amt на каждое событие: фильтр не повторяется от прохода к проходу
const jit = (amt) => rand.mul(2).sub(1).mul(amt).add(1)

// Склейка списка тактов в одну фразу: <бар1 бар2 …> — по такту на элемент.
// ВАЖНО: m() обязателен. Транспайлер REPL оборачивает в m() только
// строковые литералы; строку в переменной он не видит, и note(BASS)
// получает одну «ноту» из всего текста фразы — то есть тишину.
const phrase = (bars) => m('<' + bars.join(' ') + '>')

// ──────────────────────────────────────────────────────────────────
//  ПЭД — атмосфера, с которой всё начинается
//  Квартовые аккорды: каждая следующая нота ровно на кварту выше.
//  Корень ползёт хроматически вверх, поэтому аккорды не «относятся»
//  друг к другу и никуда не разрешаются.
// ──────────────────────────────────────────────────────────────────

const PAD = phrase([
  '[d3,g3,c4,f4]',
  '[eb3,ab3,db4,gb4]',
  '[f3,bb3,eb4,ab4]',
  '[gb3,b3,e4,a4]',
  '[g3,c4,f4,bb4]',
  '[ab3,db4,gb4,c5]',
  '[a3,d4,g4,c5]',
  '[bb3,eb4,ab4,db5]',
])

$: note(PAD)
  .s("supersaw").unison(4).detune(padDetune)
  .lpf(padCut).lpq(padReso).ftype("24db")
  .lpdepth(padLfo).lpsync(padLfoR) // срез дышит сам
  .chorus(padChorus)
  .attack(padAtk).decay(1.5).sustain(0.9).release(2.4)
  .room(verb).roomsize(verbSize)
  .gain(padVol)

// ──────────────────────────────────────────────────────────────────
//  ВОЗДУХ — ровный шум, один вдох на 16 тактов
// ──────────────────────────────────────────────────────────────────

$: s("white")
  .gain(noiseVol)
  .lpf(noiseCut).lpq(0.5)
  .lpdepth(noiseLfo).lpsync(0.0625)
  .room(verb).roomsize(verbSize)

// ──────────────────────────────────────────────────────────────────
//  БОЧКА — единственная дорожка с сэмплом bd
// ──────────────────────────────────────────────────────────────────

$: s("bd*4")
  .gain(kickVol)
  .shape(kickShape)
  .lpf(kickCut)
  .duckorbit(2).duckdepth(duck).duckattack(0.05) // дакает бас (orbit 2)

// ──────────────────────────────────────────────────────────────────
//  СТАБ — сердце даб-техно
//  4 такта по два удара (2 и 4), те же кварты, что у пэда, но выше.
//  Гласная плывёт по кругу a → e → o → u: один и тот же аккорд
//  меняет «рот» каждые 4 такта.
// ──────────────────────────────────────────────────────────────────

const STAB = phrase([
  '[~ [d4,g4,c5,f5] ~ [d4,g4,c5,f5]]',
  '[~ [eb4,ab4,db5,gb5] ~ [eb4,ab4,db5,gb5]]',
  '[~ [f4,bb4,eb5,ab5] ~ [f4,bb4,eb5,ab5]]',
  '[~ [gb4,b4,e5,a5] ~ [gb4,b4,e5,a5]]',
])

$: note(STAB)
  .s("triangle")
  .vowel("<a e o u>") // форманта: аккорд «говорит»
  .lpf(stabCut).lpq(stabReso).ftype("24db")
  .decay(stabDecay).sustain(0).release(0.14)
  .delay(stabDelay).delaytime(0.4375).delayfeedback(stabFb)
  .room(verb).roomsize(verbSize)
  .gain(stabVol)

// ──────────────────────────────────────────────────────────────────
//  БУЛЬКИ
//  5 тактов. Бульк = короткий синус, внутри которого высота падает:
//  [g5@0.25 g4@0.75] — четверть слота наверху, три четверти внизу.
//  Отсюда «буль», а не «бип». Дальше дилей, случайная панорама и
//  случайный прыжок на октаву.
// ──────────────────────────────────────────────────────────────────

const BUB = phrase([
  '[~ ~ [g5@0.25 g4@0.75] ~ ~ ~ ~ ~]',
  '[~ [d5@0.2 d4@0.8] ~ ~ ~ ~ ~ ~]',
  '[~ ~ ~ [bb5@0.3 bb4@0.7] ~ ~ ~ ~]',
  '[~ ~ ~ ~ [eb5@0.2 eb4@0.8] ~ ~ ~]',
  '[~ [f#5@0.25 f#4@0.75] ~ ~ ~ ~ [c5@0.2 c4@0.8] ~]',
])

$: note(BUB)
  .s("sine")
  .decay(0.09).sustain(0).release(0.04)
  .lpf(bubbleCut).lpq(bubbleReso)
  .sometimesBy(bubbleJump, (x) => x.add(note("12"))) // случайная октава
  .degradeBy(bubbleSparse) // случайные пропуски
  .delay(bubbleEcho).delaytime(0.4375).delayfeedback(bubbleFb)
  .pan(rand.mul(1.6).sub(0.8)) // разброс по панораме
  .room(verb).roomsize(verbSize)
  .gain(bubbleVol)

// ──────────────────────────────────────────────────────────────────
//  БАС
//  8 тактов, одна длинная нота на «и» (3-я доля), как в дабе.
//  Цвета те же, что в Берлине: тритон f#, малая секунда db, малая
//  терция eb, малая секста ab. Шершавость — не ритмом, а тембром:
//  sometimesBy навешивает crush + distort на часть нот, поэтому
//  ноты НЕ удваиваются, а просто иногда звучат грязно.
// ──────────────────────────────────────────────────────────────────

const BASS = phrase([
  '[~ ~ c2@1.5 ~@0.5]',
  '[~ ~ c2@1.5 ~@0.5]',
  '[~ ~ c2@1.5 f#2@0.5]',
  '[~ ~ db2@0.5 c2@1.5]',
  '[~ ~ c2@1.5 ~@0.5]',
  '[~ ~ eb2@1.5 ~@0.5]',
  '[~ ~ ab2@1 c2@1]',
  '[~ ~ c2@1 f#2@0.5 db2@0.5]',
])

$: stack(
     note(BASS).s("sawtooth").gain(bassVol), // то, что слышно
     note(BASS).add(note("-12")).s("sine").gain(subVol), // то, что чувствуется
   )
  .lpf(bassCut).lpq(bassReso).ftype("24db")
  .lpenv(bassEnv.mul(jit(bassRand)))
  .lpa(0.004).lpd(0.12).lpsustain(0.45)
  .lpdepth(bassLfo.mul(jit(bassRand))).lpsync(bassLfoR).lpdc(0)
  .sometimesBy(bassGrit, (x) => x.crush(bassCrush).distort(bassDist))
  .attack(0.003).decay(0.3).sustain(0.5).release(0.08)
  .orbit(2)

// ──────────────────────────────────────────────────────────────────
//  МЕЛОДИЯ
//  7 тактов, редкая и сухая. Девятые (d5, db5) — джазовый привкус,
//  f#5 — тритон, ab4 — малая секста. Ни одна нота никуда не ведёт.
// ──────────────────────────────────────────────────────────────────

const MEL = phrase([
  '[~ ~ d5 ~ ~ ~ ~ ~]',
  '[~ ~ ~ db5 ~ ~ ~ ~]',
  '[~ f#5 ~ ~ ~ ~ ~ ~]',
  '[~ ~ ~ ~ eb5 ~ ~ ~]',
  '[d5 ~ ~ ~ ~ ~ ~ ~]',
  '[~ ~ ~ ~ ~ ab4 ~ d5]',
  '[~ ~ db5 ~ ~ f#5 ~ ~]',
])

$: note(MEL)
  .s("square")
  .fm(melFm).fmh(melFmh)
  .decay(0.18).sustain(0).release(0.06)
  .lpf(melCut).lpq(4)
  .delay(melEcho).delaytime(0.375).delayfeedback(melFb)
  .room(verb).roomsize(verbSize)
  .pan(melPan.mul("<1 -1>")) // пинг-понг
  .gain(melVol)

// ──────────────────────────────────────────────────────────────────
//  ХЭТЫ — только «и», без сетки 16-х. Дробь приходит на 4-м такте
//  (lastOf), а не на первом: every() в Strudel срабатывает на нулевом
//  такте, из-за чего в 01-berlin первый же такт шёл 32-ми.
// ──────────────────────────────────────────────────────────────────

$: s("~ hh ~ hh ~ hh ~ hh")
  .gain(hatVol)
  .lpf(hatCut).hpf(masterHpf)
  .sometimesBy(hatRoll, (x) => x.ply(2))
  .lastOf(4, (x) => x.ply(2))

// ──────────────────────────────────────────────────────────────────
//  ПЕРКУССИЯ — 3 такта, поэтому не совпадает ни с басом (8),
//  ни с мелодией (7), ни с бульками (5)
// ──────────────────────────────────────────────────────────────────

const PERC = phrase([
  '[~ ~ rim ~ ~ ~ ~ ~]',
  '[~ rim ~ ~ ~ ~ ~ ~]',
  '[~ ~ ~ rim ~ ~ ~ ~]',
])

$: s(PERC)
  .gain(percVol)
  .delay(percEcho).delaytime(0.4375).delayfeedback(percFb)
  .pan("<.55 .35 .7>")
  .lpf(masterCut).lpq(masterRes).hpf(masterHpf)

// ──────────────────────────────────────────────────────────────────
//  КЛИКИ И ГЛИТЧИ — раздавленный клэп: короткий, битый, случайный.
//  degradeBy выкидывает большую часть, sometimesBy иногда превращает
//  один клик в рваный стут на 1/32.
// ──────────────────────────────────────────────────────────────────

// стутер, который НЕ затирает громкость: stut() внутри делает
// pat.gain(pow(feedback, i)), и первая копия всегда играет на 1.0 мимо
// clickVol — слой не глушится. Здесь тот же ритм, но gain умножается.
const stutGain = (times, fb, step) => (x) =>
  x.echoWith(times, step, (p, i) =>
    p.withValue((v) => ({ ...v, gain: (v.gain ?? 1) * Math.pow(fb, i) })),
  )

$: s("cp ~ ~ cp ~ ~ cp ~")
  .gain(clickVol)
  .crush(clickCrush)
  .decay(0.02).sustain(0)
  .degradeBy(clickRate)
  .sometimesBy(clickStut, stutGain(4, 0.55, 0.03125))
  .pan(rand.mul(1.6).sub(0.8))
  .lpf(clickCut).lpq(4)
  .room(verb).roomsize(verbSize)

// ──────────────────────────────────────────────────────────────────
//  ЧТО КРУТИТЬ ВО ВРЕМЯ ИГРЫ
//
//  старт:        пэд + воздух. Это уже музыка, ритма ещё нет.
//                Дальше stabVol 0.5 (появляется пульс) → kickVol 0.5 →
//                hatVol 0.25 → bassVol 0.6 + subVol 0.5 → bubbleVol 0.3
//  реверб:       verb 0.65 — уже мокро. 0.9 + verbSize 16 = собор,
//                0.15 — сухая комната. Это главная ручка этого трека.
//  стаб:         stabDelay 0.7 + stabFb 0.75 — хвост уезжает на 8 тактов
//                stabCut 400 — глухой удар из-под воды, 4000 — щёлкает
//                stabDecay 0.6 — аккорд тянется, 0.05 — только щипок
//  бульки:       bubbleFb 0.8 + bubbleEcho 0.7 — пузыри уползают
//                bubbleSparse 0.5 — редко, 0 — сыплется постоянно
//                bubbleJump 0.8 — почти всё на октаву выше (стекло)
//  бас:          bassGrit 0 — чистый, 0.9 — почти каждая нота шершавая
//                bassCrush 2 + bassDist 0.7 — злой, рвёт динамик
//                bassCut 60 + bassReso 20 — только щелчки и низ
//  пэд:          padCut 300 + padLfo 6 — аккорд плавает под водой
//                padAtk 3 — вплывает медленно, 0.02 — аккорд-удар
//  верх:         masterCut 9000 → 400 на 8 тактов и обратно — весь
//                билд-ап; masterHpf 1200 — остаются бочка, бас, пэд
//  пустота:      всё вниз, кроме noiseVol 0.2 + verb 0.9
//
//  Хочешь 909 — .bank('RolandTR909') к бочке и хэтам.
// ──────────────────────────────────────────────────────────────────
