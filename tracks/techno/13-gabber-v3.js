//  3. БОЧКА ГЛУХАЯ И ЖИРНАЯ ПО-НОВОМУ. Срез 900 → 300 Гц (верх бочки не
//     читаемость, а грязь), плюс к shape добавлен distort, плюс слой ТЕЛО
