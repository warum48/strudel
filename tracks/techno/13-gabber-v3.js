// ── ПРОПУСКИ У БОЧКИ: ЧЕМ ЭТО ДЕЛАЕТСЯ ──────────────────────────
// Отдельного механизма «пропустить удар» в движке НЕТ. Есть только
// отсутствие hap'а в паттерне, и четыре способа его получить:
//   1. `~` в мини-нотации. Именно так сделаны режимы 2 и 3 ниже: дырки
//      стоят в самой строке (`bd ~ ~ bd ~ ~ bd ~ …`) — это и есть
//      намеренный пропуск, он детерминирован и слышен как ритм.
//   2. Гейт режима. `m0…m4` — это 1 или 0 на весь такт; ветка с нулём не
//      звучит, то есть пропускает ВСЕ свои удары (и заодно не строит узлы,
//      см. `.filter(audible)`).
//   3. `euclid` — «5 из 16» само по себе раскладка с пропусками (так сделан
//      лом в 12: `s("bd").euclid(5, 16)`).
//   4. `degradeBy` — случайные пропуски. 🛑 Но у него есть яма: внутри это
//      `rand > x`, а `rand` в точке 0 равен 0 — то есть `degradeBy(0)` не
//      «выключен», он съедает самый первый удар цикла. Проверено: из
//      `bd*4` с `degradeBy(0)` остаётся 3 удара из 4. Поэтому ручки `skip`
//      на бочке здесь нет: в 08 она была бы ловушкой на первой доле.

// БОЧКА. Три решения, и все три тут:
//   • ГЛУХО — срез 300 Гц. Верх бочки не читаемость, а песок: он спорит с
//     хэтами и линией, а низа в нём нет. Крутишь вверх только в наушниках.
//   • ЖИРНО — два искажения подряд: shape (вейвшейпер, мягко ограничивает)
//     и distort (клиппинг, срывает верх). distortvol 0.7 — он же добавляет
//     громкость, поэтому .gain() стоит в ветках, а не снаружи.
//   • НИЗКО И ДЛИННО — speed 0.75 растягивает 909 вниз И в длину. Сэмпл сам
//     длиннее не станет: длину даёт слой ТЕЛО ниже.
// Громкость внутри каждой ветки: .gain() СТАВИТ громкость, поэтому общий
// .gain(drums.kick.vol) снаружи стёр бы гейты режимов.
// Ритм: 0/1 — четыре в пол, 2 — лом, 3 — брейк (половинный темп), 4 — ролл
// отдельной дорожкой.
$: stack(
     s("bd*4").gain(drums.kick.vol.mul(m01)),
     s("bd ~ ~ bd ~ ~ bd ~ ~ ~ bd ~ bd ~ ~ ~").gain(drums.kick.vol.mul(m2)),
     s("bd ~ ~ ~ ~ ~ ~ ~ bd ~ ~ ~ ~ ~ ~ ~").gain(drums.kick.vol.mul(m3).mul(1.1)),
   )
  .lpf(drums.kick.cut).lpq(1)
  .speed(drums.kick.tune)
  .shape(drums.kick.shape)
  .distort(drums.kick.dist).distortvol(0.7)
  .decay(drums.kick.decay).sustain(0).release(0.08)
  .duckorbit(2).duckdepth(duck).duckattack(0.03)
  ._pianoroll()
  .filter(audible)

// ТЕЛО БОЧКИ — то, чего у сэмпла нет: длина. 909-бочка кончается за 200 мс,
// и сколько ей decay ни ставь, длиннее она не станет. Поэтому длина делается
// слоем: синус по корню, спад до bodyDecay и ПАДЕНИЕ ПИТЧА на атаке
// (penv + panchor(0) + psustain(0) — прыжок вверх и съезд к ноте за pdecay,
// тот же приём, что у хувера). Это и есть «бум», а не «тук».
// Ритм — тот же, что у бочки-якоря (mK: во всех режимах кроме ролла).
$: stack(
     note(DRONE).s("sine").struct("x ~ ~ ~ x ~ ~ ~ x ~ ~ ~ x ~ ~ ~").gain(drums.kick.bodyLevel.mul(drums.kick.vol).mul(m01)),
     note(DRONE).s("sine").struct("x ~ ~ x ~ ~ x ~ ~ ~ x ~ x ~ ~ ~").gain(drums.kick.bodyLevel.mul(drums.kick.vol).mul(m2)),
     note(DRONE).s("sine").struct("x ~ ~ ~ ~ ~ ~ ~ x ~ ~ ~ ~ ~ ~ ~").gain(drums.kick.bodyLevel.mul(drums.kick.vol).mul(m3)),
   )
  .lpf(drums.kick.cut.mul(0.45)).lpq(1)
  .penv(drums.kick.bodyDrop).panchor(0).pattack(0.002).pdecay(0.09).psustain(0).pcurve(1)
  .attack(0.002).decay(drums.kick.bodyDecay).sustain(0).release(0.12)
  .orbit(2)
  .filter(audible)

// РОЛЛ — режим 4: 16-е бочки. 180 BPM на 16-х = 12 ударов в секунду,
// поэтому своя дорожка: здесь нужен короткий decay, иначе удары слипаются
// в один гул. Без сайдчейна — бочка сплошная, дакать нечего.
