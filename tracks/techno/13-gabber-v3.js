// 🛑 НОЛЬ НА РУЧКЕ — ЭТО НЕ БЕСПЛАТНО. Событие с gain 0 всё равно проходит
// весь путь: сэмпл грузится, узлы и AudioWorklet строятся, орбита и дилей
// получают сигнал — просто всё умножается на ноль. А у нас по умолчанию ВСЕ
// ударные стоят в нуле, и вдобавок в каждом стеке четыре-пять веток режима,
// из которых все кроме одной всегда с gain 0.
//
// Поэтому каждая дорожка кончается `.filter(audible)`: hap с нулевой
// громкостью не доходит до триггера вообще — его не играют, не грузят, не
// строят. Гейт стоит ПОСЛЕ `._pianoroll()` намеренно: виджет рисует «тень»
// паттерна, снятую ДО фильтра, поэтому ролл показывает ритм и на нулевой
// громкости. Тип проверяем: если gain пришёл не числом (сигнал/паттерн),
// дорожку не глушим.
const audible = (hap) => {
  const g = hap.value?.gain
  return typeof g !== 'number' || g > 0.001
}

