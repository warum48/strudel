//     незачем — смотреть надо на линию и на бочку.
//  6. ПРОПУСКИ УДАРОВ — ТОЛЬКО НА УРОВНЕ ПАТТЕРНА. В движке такого
//     механизма нет: superdough не умеет «пропустить» событие, он умеет его
//     сыграть. Всё, что похоже на пропуск, — это отсутствие hap'а в паттерне:
//     `~` в мини-нотации (режимы 2 и 3 ниже), гейты режимов (`m0…m4`),
//     `euclid`, `degradeBy`. Ручки `skip` тут нет намеренно — см. блок
//     ПРОПУСКИ У БОЧКИ ниже.
//
//  ── ПОЧЕМУ ЭТО ГАББЕР, А НЕ ПРОСТО БЫСТРЫЙ ТЕХНО ────────────────
//  Три вещи вместе, и ни одна из них по отдельности габбера не даёт:
//   1. БОЧКА РАСТЯНУТА ВНИЗ. speed 0.75 опускает 909-бочку почти на четыре
//      полутона и удлиняет её. Это не «бочка с фильтром», это другая бочка.
