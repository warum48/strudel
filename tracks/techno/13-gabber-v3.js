  '[a3,c4,e4]',
  '[db4,f4]',     // Bbm без корня, октавой выше линии
  '[db4,f4]',
  '[a3,c4,e4]',
  '[a3,c4,g4]',   // Am7 без квинты
  '[db4,g4]',     // Bbm add6 без корня
  '[db4,f4]',     // корень держат дрон и бас
