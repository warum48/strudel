// ══════════════════════════════════════════════════════════════════
//  DNB LIVE RIG v2  ·  Strudel  ·  174 BPM
//
//  Что нового против v1:
//    · mode — переключатель ритма: 0 всё / 1 без перкуссии /
//      2 без перкуссии и снейра (одна ручка глушит сразу 3 дорожки)
//    · мелодия — 4 ноты на 2 такта, сухая, слегка мимо тональности
//    · злой саб — раз в 4 такта, жирный, с падением f2 → f1
//
//  Как играть:
//    1. открой https://strudel.cc
//    2. вставь весь файл в редактор
//    3. Ctrl+Enter
//    4. тяни слайдеры прямо в коде — звук меняется на лету
// ══════════════════════════════════════════════════════════════════

setcpm(174 / 4) // 174 BPM; один цикл = один такт

// ──────────────────────────────────────────────────────────────────
//  ПУЛЬТ   slider(значение, минимум, максимум, шаг)
// ──────────────────────────────────────────────────────────────────

// ГЛАВНЫЙ ПЕРЕКЛЮЧАТЕЛЬ РИТМА.
// Кнопок в Strudel нет — только слайдеры, поэтому это слайдер с шагом 1
// на три позиции: тащишь вправо и половина грува отваливается.
//   0 — всё играет
//   1 — перкуссия (хэты, открытые хэты, рим/клэп) заглушена
//   2 — плюс снейр и призрачные снейры
const mode    = slider(0, 0, 2, 1)
const percOn  = mode.fmap((m) => (m < 1 ? 1 : 0))
const snareOn = mode.fmap((m) => (m < 2 ? 1 : 0))

const kickVol  = slider(0.95, 0, 1.3, 0.01)   // бочка
const kickCut  = slider(0, 0, 0.9, 0.01)      // убрать вторую бочку (0 = обе)
const snareVol = slider(0.95, 0, 1.3, 0.01)   // снейр
const snareRev = slider(0.3, 0, 1, 0.01)      // реверб на снейре
const ghostVol = slider(0.2, 0, 0.9, 0.01)    // призрачные снейры
const hatVol   = slider(0.45, 0, 1, 0.01)     // закрытые хэты
const hatRoll  = slider(0, 0, 1, 0.01)        // вероятность «дробей» на хэтах
const ohVol    = slider(0.22, 0, 0.9, 0.01)   // открытые хэты
const percVol  = slider(0.25, 0, 0.9, 0.01)   // римшот / клэп
const percEcho = slider(0.25, 0, 0.8, 0.01)   // дилей на перкуссии
const radio    = slider(0, 0, 1500, 10)       // хайпасс на барабаны (билд-ап)

const bVol     = slider(0.9, 0, 1.3, 0.01)    // бас
const bCut     = slider(320, 80, 4000, 10)    // срез фильтра баса
const bReso    = slider(7, 0, 24, 0.5)        // резонанс
const bEnv     = slider(3.5, 0, 8, 0.1)       // глубина фильтр-огибающей
const bDet     = slider(3, 0, 24, 0.5)        // расстройка риза (ширина)
const bDrive   = slider(0.15, 0, 0.9, 0.01)   // дисторшн баса
const bDuck    = slider(0.85, 0, 1, 0.01)     // сайдчейн баса от бочки
const bRoll    = slider(0, 0, 1, 0.01)        // вероятность дабл-нот баса
const subVol   = slider(0.3, 0, 0.8, 0.01)    // саб-синус

const melVol   = slider(0.42, 0, 1, 0.01)     // мелодия
const melCut   = slider(1600, 200, 6000, 20)  // срез мелодии
const melEcho  = slider(0.28, 0, 0.8, 0.01)   // дилей мелодии

const evilVol   = slider(0.75, 0, 1.3, 0.01)  // злой саб
const evilDrive = slider(0.5, 0, 0.95, 0.01)  // его дисторшн
const evilCut   = slider(150, 60, 900, 5)     // срез его пилы

const padVol   = slider(0.18, 0, 0.8, 0.01)   // пэд
const padCut   = slider(900, 200, 6000, 20)   // срез пэда

// ──────────────────────────────────────────────────────────────────
//  БАРАБАНЫ
// ──────────────────────────────────────────────────────────────────

// бочка: первая доля всегда, «и» третьей — по слайдеру kickCut
// (две дорожки, потому что degradeBy(0) съедает событие на t=0)
$: stack(
     s("bd ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~"),
     s("~ ~ ~ ~ ~ ~ ~ ~ ~ ~ bd ~ ~ ~ ~ ~").degradeBy(kickCut),
   )
  .gain(kickVol)
  .shape(0.35)
  .duckorbit(2).duckdepth(bDuck).duckattack(0.06) // дакает бас (orbit 2)
  .hpf(radio)

// снейр: 2 и 4 (глохнет на mode = 2)
$: s("~ ~ ~ ~ sd ~ ~ ~ ~ ~ ~ ~ sd ~ ~ ~")
  .gain(snareVol.mul(snareOn))
  .room(snareRev)
  .hpf(radio)

// призрачные снейры — та самая «нервность» брейкбита (тоже на mode = 2)
$: s("~ ~ ~ sd:2 ~ ~ ~ sd:3 ~ ~ ~ ~ ~ ~ rim ~")
  .gain(ghostVol.mul(snareOn))
  .pan("[.35 .65]*8")

// закрытые хэты с акцентами; hatRoll добавляет дробей (глохнут на mode = 1)
$: s("hh*16")
  .gain(hatVol.mul("[1 .35 .6 .35]*4").mul(percOn))
  .sometimesBy(hatRoll, x => x.ply(2))

// открытые хэты на «и»
$: s("~ oh ~ oh ~ oh ~ oh")
  .gain(ohVol.mul(percOn))
  .shape(0.2)

// перкуссия с эхом
$: s("~ ~ rim ~ ~ ~ ~ ~ ~ ~ ~ ~ cp ~ ~ ~")
  .gain(percVol.mul(percOn))
  .delay(percEcho).delaytime(0.1875).delayfeedback(0.45)
  .pan("[.65 .35]*8")
  .hpf(radio)

// ──────────────────────────────────────────────────────────────────
//  МЕЛОДИЯ
//  Четыре ноты на два такта, всё остальное — паузы.
//  f — центр; b3 от f4 — тритон, e3 против eb4 — малая секунда.
//  Доминанты нет, к тонике не разрешается: специально никуда не идёт.
// ──────────────────────────────────────────────────────────────────
$: note("<[~ ~ ~ f4 ~ ~ ~ ~ ~ ~ b3 ~ ~ ~ ~ ~] [~ ~ eb4 ~ ~ ~ ~ ~ e3 ~ ~ ~ ~ ~ ~ ~]>")
  .s("square")
  .lpf(melCut).lpq(3)
  .decay(0.12).sustain(0).release(0.05)
  .delay(melEcho).delaytime(0.1875).delayfeedback(0.25)
  .room(0.12)
  .gain(melVol)

// ──────────────────────────────────────────────────────────────────
//  БАС  (orbit 2 — его дакает бочка)
// ──────────────────────────────────────────────────────────────────

// риз: supersaw + детюн, фильтр с огибающей, дисторшн
$: note("f1 ~ ~ f1 ~ f1 ~ ~")
  .s("supersaw")
  .detune(bDet)
  .lpf(bCut).lpq(bReso).lpenv(bEnv).lpa(0.004).lpd(0.16)
  .distort(bDrive)
  .sometimesBy(bRoll, x => x.ply(2))
  .gain(bVol)
  .orbit(2)

// саб-синус: тот же ритм, только низ
$: note("f1 ~ ~ f1 ~ f1 ~ ~")
  .s("sine")
  .attack(0.004).decay(0.18).sustain(0.7).release(0.06)
  .gain(subVol)
  .orbit(2)

// ──────────────────────────────────────────────────────────────────
//  ЗЛОЙ САБ
//  Раз в 4 такта, на первом такте фразы: f2 → f1 за две доли,
//  дальше три такта тишины. Синус даёт низ, сатурированная пила —
//  то, что слышно на ноутбучных динамиках.
// ──────────────────────────────────────────────────────────────────
$: stack(
     note("[f2 f1] ~ ~ ~").s("sine"),
     note("[f2 f1] ~ ~ ~").s("sawtooth").lpf(evilCut).lpq(9).lpenv(5),
   )
  .slow(4)
  .attack(0.002).decay(0.9).sustain(0).release(0.15)
  .distort(evilDrive)
  .gain(evilVol)
  .orbit(2)

// ──────────────────────────────────────────────────────────────────
//  ПЭД  (Fm — Ab — Cm — Fm, один аккорд на 2 такта)
// ──────────────────────────────────────────────────────────────────
$: note("<[f2,c3,eb3] [ab1,c2,eb3] [c2,eb2,g2] [c2,f2,ab2]>")
  .s("sawtooth")
  .lpf(padCut).lpq(2)
  .attack(0.4).release(0.8)
  .room(0.6)
  .gain(padVol)
  .slow(2)

// ──────────────────────────────────────────────────────────────────
//  ЧТО КРУТИТЬ ВО ВРЕМЯ ИГРЫ
//
//  ритм:        mode 1 — убрать перкуссию, mode 2 — оставить только бочку и бас
//  билд-ап:     radio → 800-1500, bCut вниз, потом всё обратно в дроп
//  дроп:        mode 0, kickCut 0, bDuck 0.85, bCut 250-400, bDrive 0.2-0.4
//  лом:         hatRoll 0.4-0.6, bRoll 0.5, percEcho 0.5
//  пустота:     mode 2, ghostVol 0, padVol 0.4, melVol 0.6
//  злой саб:    evilVol 1.1, evilDrive 0.8, evilCut 300 — рычит на каждом 4-м такте
//  мелодия:     melCut 500-800 — уходит в далёкое радио, 3000 — режет уши
//
//  Хочешь другой кит — добавь .bank('RolandTR909') к дорожкам бочки/снейра.
// ──────────────────────────────────────────────────────────────────
