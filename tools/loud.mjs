// Треки этой серии СТАРТУЮТ ТИХО: атмосфера звучит, а все ударные и мелодии
// стоят в нуле. Плюс каждая дорожка кончается `.filter(audible)` — hap с
// нулевой громкостью вообще не доходит до триггера (иначе он строил бы узлы и
// AudioWorklet'ы в пустоту). Для проверок это значит: на дефолтных ручках
// видно пустоту, а не аранжировку.
//
// Поэтому все инструменты, которые смотрят на СЕТКУ (verify, doubles, modes,
// cpu, latch), принудительно поднимают громкости до 0.8 — проверяется
// аранжировка, а не положение ручек. Исключение — `gains.mjs`: он ровно за тем
// и нужен, чтобы убедиться, что на нулях тихо, ему поднимать нельзя.
//
// Два стиля объявления, оба надо поднять:
//   старый (10, 11):   const kickVol = slider(0, 0, 0.5, 0.01)
//   новый (12, дерево): vol: slider(0, 0, 0.5, 0.01)
export const loudVolumes = (code) =>
  code
    .replace(/const\s+(\w*[Vv]ol\w*)\s*=\s*slider\(\s*[^,\n]+/g, (m) =>
      m.replace(/slider\(\s*[^,\n]+/, 'slider(0.8'),
    )
    .replace(/\bvol:\s*slider\(\s*[^,\n]+/g, (m) => m.replace(/slider\(\s*[^,\n]+/, 'slider(0.8'));
